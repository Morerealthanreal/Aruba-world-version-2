#!/usr/bin/env python3
"""Point hero GLB loads at a per-place rev.

The bundle requests ./models/hero/<id>.glb?v=<rev>, where rev is the "rev"
field on refs/places/_registry/<id>.json, or the fallback stamp already
baked into the bundle when that place has no rev. Set "rev" on the one
place whose GLB changed. Do not edit this file, game/index.html, or the
bundle to publish a landmark.

Idempotent. Also enables the Draco decoder for compressed hero GLBs.
"""
import os
import re

D = os.path.join(os.path.dirname(os.path.abspath(__file__)), "../game/")
f = D + "assets/" + re.search(
    r"index-[A-Za-z0-9_-]+\.js", open(D + "index.html").read()
).group(0)
s = open(f).read()
if "n.rev||`" in s:
    print("herover: per-place rev already on")
else:
    pat = r"dm\.loadAsync\(`\./`\+n\.glb\.replace\(/\^\\\.\?\\//,``\)\+`\?v=(\w+)`\)"
    found = re.search(pat, s)
    assert found, "hero load site not found"
    stamp = found.group(1)
    repl = (
        "dm.loadAsync(`./`+n.glb.replace(/^\\.?\\//,``)+`?v=`+(n.rev||`%s`))"
        % stamp
    )
    s2, n = re.subn(pat, repl, s, count=1)
    assert n == 1, "hero load site not patched"
    open(f, "w").write(s2)
    print("herover: per-place rev, fallback", stamp)
    s = s2
if "dm=new Nf().setDRACOLoader" not in s:
    assert s.count("var dm=new Nf,") == 1
    s = s.replace(
        "var dm=new Nf,",
        "var dm=new Nf().setDRACOLoader(new Vp().setDecoderPath(`./draco/`)),",
    )
    open(f, "w").write(s)
    print("herover: draco on")
