def write_manifest(updates, extra):
    manifest = json.loads(MANIFEST.read_text())
    by_id = {e["id"]: e for e in extra}
    seen = set()
    for entry in manifest:
        gid = entry.get("id")
        if gid in updates:
            tris, textures = updates[gid]
            entry["tris"] = {f"{gid}_lod0": tris[0], f"{gid}_lod1": tris[1]}
            entry["textures"] = textures
            entry["status"] = "v5-oranjestad-smith"
            entry["frame"] = FRAME
            entry["ref_sources"] = REFS
            seen.add(gid)
        if gid in by_id:
            seen.add(gid)
    missing = [gid for gid in updates if gid not in {e.get("id") for e in manifest}]
    if missing:
        raise SystemExit(f"missing heroes {missing}")
    manifest = [e for e in manifest if e.get("id") not in by_id]
    manifest.extend(extra)
    text = json.dumps(manifest, indent=1)
    if text.endswith("\n"):
        text = text[:-1]
    MANIFEST.write_text(text)
    print(f"manifest hotels {len(updates)} new {len(extra)}")


