def quad_out(prim, p0, p1, p2, p3, color, prefer):
    n = Prim._n(p0, p1, p2)
    if n is None:
        return
    if n[0] * prefer[0] + n[1] * prefer[1] + n[2] * prefer[2] >= 0:
        prim.quad(p0, p1, p2, p3, color)
    else:
        prim.quad(p1, p0, p3, p2, color)


def point_on(a, b, outward, t, y, proud, origin, h0):
    dx, dz = b[0] - a[0], b[1] - a[1]
    L = hypot(dx, dz) or 1.0
    ox, oz = origin
    return (
        a[0] + dx / L * t + outward[0] * proud - ox,
        y - h0,
        a[1] + dz / L * t + outward[1] * proud - oz,
    )


def span(prim, a, b, outward, t0, t1, y0, y1, color, origin, h0, proud):
    if t1 - t0 < 0.2 or y1 - y0 < 0.08:
        return
    quad_out(
        prim,
        point_on(a, b, outward, t0, y0, proud, origin, h0),
        point_on(a, b, outward, t1, y0, proud, origin, h0),
        point_on(a, b, outward, t1, y1, proud, origin, h0),
        point_on(a, b, outward, t0, y1, proud, origin, h0),
        color,
        (outward[0], 0.12, outward[1]),
    )


def sign_span(signs, uv, a, b, outward, t0, t1, y0, y1, origin, h0, proud):
    u0, v0, u1, v1 = uv
    p0 = point_on(a, b, outward, t0, y0, proud, origin, h0)
    p1 = point_on(a, b, outward, t1, y0, proud, origin, h0)
    p2 = point_on(a, b, outward, t1, y1, proud, origin, h0)
    p3 = point_on(a, b, outward, t0, y1, proud, origin, h0)
    n = Prim._n(p0, p1, p2)
    if n is None:
        return
    prefer = outward[0] * n[0] + outward[1] * n[2]
    if prefer >= 0:
        signs.quad(p0, p1, p2, p3, (1, 1, 1), ((u0, v0), (u1, v0), (u1, v1), (u0, v1)))
    else:
        signs.quad(p1, p0, p3, p2, (1, 1, 1), ((u1, v0), (u0, v0), (u0, v1), (u1, v1)))


def paint_sign(atlas, text, bg, fg):
    w, h = 512, 96
    x, y = 8, 8 + atlas._next * (h + 8)
    atlas._next += 1
    atlas.draw.rectangle((x, y, x + w - 1, y + h - 1), fill=bg)
    atlas.draw.rectangle((x + 6, y + 6, x + w - 7, y + h - 7), outline=fg, width=4)
    label = text.upper()
    size = 54
    font = ImageFont.truetype(FONT, size)
    for _ in range(6):
        bbox = atlas.draw.textbbox((0, 0), label, font=font)
        tw, th = bbox[2] - bbox[0], bbox[3] - bbox[1]
        if tw <= w - 28 and th <= h - 16:
            break
        size = max(18, int(size * min((w - 28) / max(tw, 1), (h - 16) / max(th, 1))))
        font = ImageFont.truetype(FONT, size)
    atlas.draw.text((x + (w - tw) / 2, y + (h - th) / 2 - 2), label, fill=fg, font=font)
    return atlas._uv(x, y, w, h)


def faces(poly):
    c = centroid(poly)
    out = []
    ccw = poly_area(poly) > 0
    for i in range(len(poly)):
        a, b = poly[i], poly[(i + 1) % len(poly)]
        dx, dz = b[0] - a[0], b[1] - a[1]
        L = hypot(dx, dz)
        if L < 6:
            continue
        ln = (-dz / L, dx / L)
        outward = ln if not ccw else (dz / L, -dx / L)
        out.append((a, b, outward, L))
    return out


def hip(prim, poly, origin, h0, y_eave, rise, color):
    c = centroid(poly)
    peak = (c[0] - origin[0], y_eave + rise - h0, c[1] - origin[1])
    for i in range(len(poly)):
        p, q = poly[i], poly[(i + 1) % len(poly)]
        e0 = (p[0] - origin[0], y_eave - h0, p[1] - origin[1])
        e1 = (q[0] - origin[0], y_eave - h0, q[1] - origin[1])
        n = Prim._n(peak, e0, e1)
        if n is None:
            continue
        if n[1] >= 0:
            prim.tri(peak, e0, e1, color)
        else:
            prim.tri(peak, e1, e0, color)


def street_gable(paint, a, b, outward, eave, origin, h0, color):
    """A tile triangle and a sloping eave the sidewalk can see."""
    dx, dz = b[0] - a[0], b[1] - a[1]
    L = hypot(dx, dz) or 1.0
    mid = L * 0.5
    peak = point_on(a, b, outward, mid, eave + 3.4, 0.35, origin, h0)
    left = point_on(a, b, outward, 0.4, eave, 0.2, origin, h0)
    right = point_on(a, b, outward, L - 0.4, eave, 0.2, origin, h0)
    n = Prim._n(left, right, peak)
    if n is not None:
        if n[0] * outward[0] + n[2] * outward[1] >= 0:
            paint.tri(left, right, peak, color)
        else:
            paint.tri(right, left, peak, color)
    # overhang the camera sees under the eave
    p0 = point_on(a, b, outward, 0.3, eave - 0.05, 0.15, origin, h0)
    p1 = point_on(a, b, outward, L - 0.3, eave - 0.05, 0.15, origin, h0)
    p2 = point_on(a, b, outward, L - 0.3, eave - 1.15, 2.4, origin, h0)
    p3 = point_on(a, b, outward, 0.3, eave - 1.15, 2.4, origin, h0)
    quad_out(paint, p0, p1, p2, p3, color, (outward[0], 0.35, outward[1]))


def dress_face(paint, glass, a, b, outward, ground, eave, origin, h0, floors, arch=False):
    L = hypot(b[0] - a[0], b[1] - a[1])
    storey = (eave - ground) / floors
    # Ground floor openings.
    bay = 3.6
    n = max(2, int(L / bay))
    for k in range(n):
        t0 = L * k / n
        t1 = L * (k + 1) / n
        gap = (t1 - t0) * 0.16
        mid0, mid1 = t0 + gap, t1 - gap
        top = ground + storey * 0.78
        span(glass, a, b, outward, mid0, mid1, ground + 0.25, top, NAVY if arch else GLASS, origin, h0, 0.18)
        if arch:
            span(paint, a, b, outward, mid0 - 0.18, mid0, ground + 0.15, top + 0.4, WHITE, origin, h0, 0.3)
            span(paint, a, b, outward, mid1, mid1 + 0.18, ground + 0.15, top + 0.4, WHITE, origin, h0, 0.3)
            span(paint, a, b, outward, mid0 - 0.08, mid1 + 0.08, top - 0.02, top + 0.46, WHITE, origin, h0, 0.34)
    # Upper floors: a full-height window behind a balcony the sidewalk can see.
    for f in range(1, floors):
        y0 = ground + storey * f
        span(paint, a, b, outward, 0.25, L - 0.25, y0, y0 + 0.16, RAIL, origin, h0, 1.15)
        span(paint, a, b, outward, 0.25, L - 0.25, y0 + 0.9, y0 + 1.04, RAIL, origin, h0, 1.1)
        span(glass, a, b, outward, 0.55, L - 0.55, y0 + 0.85, y0 + 2.25, GLASS, origin, h0, 0.16)
        step = max(4.6, L / max(3, int(L / 5.2)))
        t = 0.35
        while t < L - 0.4:
            span(paint, a, b, outward, t, t + 0.55, y0 + 0.2, y0 + storey * 0.9, WHITE, origin, h0, 0.36)
            t += step


def build_hotel(entry, floors, wall, sign_text, sign_bg, sign_fg, arch=False):
    poly = clean_poly([(p[0], p[1]) for p in entry["hide_footprint"]])
    c = centroid(poly)
    ox, oz = entry["x"], entry["z"]
    h0 = height_at(ox, oz)
    origin = (ox, oz)
    ground = height_at(c[0], c[1])
    if ground < 1.0:
        ground = h0
    eave = ground + (3.15 * floors)
    paint, glass, signs, lod = Prim(), Prim(), Prim(), Prim()
    atlas = Atlas(size=1024)
    atlas._next = 0
    extrude_walls(paint, poly, ground - 0.4, eave, wall, origin, h0)
    hip(paint, poly, origin, h0, eave, 2.8 if floors <= 3 else 2.2, ROOF)
    water = [f for f in faces(poly) if f[2][0] < -0.45]
    if not water:
        water = sorted(faces(poly), key=lambda f: f[3], reverse=True)[:1]
    for a, b, outward, L in water:
        dress_face(paint, glass, a, b, outward, ground, eave, origin, h0, floors, arch=arch)
        street_gable(paint, a, b, outward, eave, origin, h0, ROOF)
    # The longest water face carries the name.
    host = max(water, key=lambda f: f[3])
    a, b, outward, L = host
    uv = paint_sign(atlas, sign_text, sign_bg, sign_fg)
    mid = L * 0.5
    # A tall board on a floor the boulevard camera actually sees.
    if floors >= 5:
        sign_y, sh, sw = ground + 3.15 * 2.15, 3.3, min(16.0, L * 0.46)
    elif floors > 2:
        sign_y, sh, sw = ground + 3.15 * 1.15, 2.8, min(12.0, L * 0.4)
    else:
        sign_y, sh, sw = ground + 3.15 * 0.78, 3.4, min(12.0, L * 0.42)
    sign_span(
        signs,
        uv,
        a,
        b,
        outward,
        mid - sw / 2,
        mid + sw / 2,
        sign_y,
        sign_y + sh,
        origin,
        h0,
        0.9,
    )
    extrude_walls(lod, poly, ground, eave + 1.5, wall, origin, h0)
    return pack(entry["id"], paint, glass, signs, atlas, lod)


def crane(paint, x, z, origin, h0, cargo=None):
    """A ship-to-shore gantry seen from L.G. Smith. Boom runs west, over the water."""
    g = height_at(x, z)
    y0 = g - h0
    ox, oz = origin

    def b(cx, cy, cz, sx, sy, sz, color):
        box(paint, cx - ox, cy, cz - oz, sx, sy, sz, color)

    # Portal legs on a short rail, sill at the top, waterside leg set back.
    for s in (-4.6, 4.6):
        b(x, y0 + 16.0, z + s, 1.4, 32.0, 1.4, YELLOW)
        b(x - 8.0, y0 + 12.0, z + s, 0.9, 24.0, 0.9, YELLOW)
    b(x, y0 + 0.28, z, 2.4, 0.4, 12.4, STEEL)
    b(x - 3.8, y0 + 31.2, z, 2.6, 1.2, 11.4, YELLOW)
    b(x, y0 + 32.6, z, 1.15, 0.55, 11.6, YELLOW)
    # Machinery house, counterweight, and the land-side of the boom.
    b(x + 9.0, y0 + 31.5, z, 16.0, 1.25, 1.7, YELLOW)
    b(x + 15.2, y0 + 28.2, z, 3.4, 5.2, 3.6, CABIN)
    b(x + 16.0, y0 + 24.6, z, 2.4, 3.4, 5.0, YELLOW)
    # Two chords so the outreach reads as a truss, not a single plank.
    b(x - 16.0, y0 + 31.8, z, 36.0, 0.7, 1.2, YELLOW)
    b(x - 15.0, y0 + 29.2, z, 32.0, 0.42, 0.62, YELLOW)
    for k in range(6):
        b(x - 4.0 - k * 5.2, y0 + 30.5, z, 0.35, 2.4, 0.35, YELLOW)
    # Mast and forestay.
    b(x + 2.2, y0 + 39.0, z, 0.55, 14.0, 0.55, YELLOW)
    b(x - 6.0, y0 + 36.2, z, 18.0, 0.28, 0.28, YELLOW)
    # Trolley, falls and spreader over the water.
    b(x - 26.0, y0 + 30.6, z, 2.4, 0.85, 1.7, YELLOW)
    b(x - 26.6, y0 + 20.5, z, 0.16, 18.0, 0.16, STEEL)
    b(x - 25.2, y0 + 20.5, z, 0.16, 18.0, 0.16, STEEL)
    b(x - 25.9, y0 + 11.2, z, 3.4, 0.42, 1.35, YELLOW)
    if cargo:
        b(x - 25.9, y0 + 8.6, z, 6.0, 2.5, 2.4, cargo)


def build_cranes():
    pads = [(-8336.0, -385.0), (-8344.0, -350.0), (-8332.0, -318.0)]
    keep = []
    for x, z in pads:
        h = height_at(x, z)
        if h < 3.0:
            print(f"  crane skip {x:.0f},{z:.0f} h={h:.2f}")
            continue
        keep.append((x, z, h))
    if len(keep) < 2:
        raise SystemExit("not enough quay for cranes")
    ox = sum(p[0] for p in keep) / len(keep)
    oz = sum(p[1] for p in keep) / len(keep)
    h0 = height_at(ox, oz)
    paint = Prim()
    for i, (x, z, _h) in enumerate(keep):
        crane(paint, x, z, (ox, oz), h0, cargo=RED if i == 1 else None)
        print(f"  crane {x:.0f},{z:.0f} h={_h:.2f}")
    lod = Prim()
    for x, z, h in keep:
        box(lod, x - ox, (h - h0) + 16, z - oz, 2.2, 32.0, 2.2, YELLOW)
        box(lod, x - ox - 10, (h - h0) + 31, z - oz, 28.0, 0.8, 1.2, YELLOW)
    glb = Glb("ora_cranes")
    glb.mat("paint", rough=0.62, metal=0.25)
    glb.add(paint, "paint")
    glb.lod1_prim = lod
    glb.name = "ora_cranes"
    data, tris = glb.pack()
    path = HERO / "ora_cranes.glb"
    path.write_bytes(data)
    if audit(path):
        raise SystemExit("ora_cranes degenerate")
    print(f"wrote ora_cranes.glb tris {tris}")
    entry = manifest_entry(
        "ora_cranes",
        "Paardenbaai harbour gantry cranes",
        ox,
        oz,
        tris,
        0,
        [],
        520,
    )
    entry["status"] = "v5-oranjestad-smith"
    entry["frame"] = FRAME
    entry["ref_sources"] = REFS
    entry["geo_source"] = "Paardenbaai quay edge from the terrain, north of the cruise berths"
    return entry


def _unit(v):
    L = math.sqrt(v[0] * v[0] + v[1] * v[1] + v[2] * v[2]) or 1.0
    return (v[0] / L, v[1] / L, v[2] / L)


def sweep(prim, pts, normal_xz, hw, ht, color):
    """Thick strip. normal_xz is the thickness direction on the ground."""
    nx, nz = normal_xz
    sections = []
    for i, p in enumerate(pts):
        if i == 0:
            raw = (pts[1][0] - p[0], pts[1][1] - p[1], pts[1][2] - p[2])
        elif i == len(pts) - 1:
            raw = (p[0] - pts[i - 1][0], p[1] - pts[i - 1][1], p[2] - pts[i - 1][2])
        else:
            raw = (
                pts[i + 1][0] - pts[i - 1][0],
                pts[i + 1][1] - pts[i - 1][1],
                pts[i + 1][2] - pts[i - 1][2],
            )
        t = _unit(raw)
        wx = t[1] * nz
        wy = t[2] * nx - t[0] * nz
        wz = -t[1] * nx
        wL = math.sqrt(wx * wx + wy * wy + wz * wz) or 1.0
        wx, wy, wz = wx / wL * hw, wy / wL * hw, wz / wL * hw
        tx, tz = nx * ht, nz * ht
        sections.append(
            (
                (p[0] + wx + tx, p[1] + wy, p[2] + wz + tz),
                (p[0] - wx + tx, p[1] - wy, p[2] - wz + tz),
                (p[0] - wx - tx, p[1] - wy, p[2] - wz - tz),
                (p[0] + wx - tx, p[1] + wy, p[2] + wz - tz),
            )
        )
    for a, b in zip(sections, sections[1:]):
        prim.quad(a[1], a[0], b[0], b[1], color)
        prim.quad(a[3], a[2], b[2], b[3], color)
        prim.quad(a[0], a[3], b[3], b[0], color)
        prim.quad(a[2], a[1], b[1], b[2], color)
    cap0, cap1 = sections[0], sections[-1]
    prim.quad(cap0[0], cap0[1], cap0[2], cap0[3], color)
    prim.quad(cap1[3], cap1[2], cap1[1], cap1[0], color)


def shaft(prim, y0, y1, s0, s1, color):
    def ring(y, s):
        h = s / 2
        return [(-h, y, -h), (h, y, -h), (h, y, h), (-h, y, h)]

    a, b = ring(y0, s0), ring(y1, s1)
    for i in range(4):
        j = (i + 1) % 4
        # Outward: bottom-right, bottom-left, top-left, top-right when seen from outside.
        prim.quad(a[j], a[i], b[i], b[j], color)
    prim.quad(b[0], b[3], b[2], b[1], color)


def disc(prim, radius, y0, y1, color, n=20):
    for i in range(n):
        a0 = math.tau * i / n
        a1 = math.tau * (i + 1) / n

        def p(a, y, rad):
            return (math.cos(a) * rad, y, math.sin(a) * rad)

        prim.quad(p(a0, y1, 0.3), p(a1, y1, 0.3), p(a1, y1, radius), p(a0, y1, radius), color)
        prim.quad(p(a0, y0, radius), p(a1, y0, radius), p(a1, y1, radius), p(a0, y1, radius), color)


def build_obelisk():
    """White needle and the black-and-white curb at the Renaissance roundabout."""
    paint = Prim()
    n = 18
    inner, outer = 3.5, 5.4
    for i in range(n):
        a0 = math.tau * i / n
        a1 = math.tau * (i + 1) / n
        col = INK if i % 2 == 0 else CHK_W

        def p(a, r, y, col=col):
            return (math.cos(a) * r, y, math.sin(a) * r)

        paint.quad(p(a0, inner, 0.78), p(a1, inner, 0.78), p(a1, outer, 0.78), p(a0, outer, 0.78), col)
        paint.quad(p(a0, outer, 0.06), p(a1, outer, 0.06), p(a1, outer, 0.78), p(a0, outer, 0.78), col)
        paint.quad(p(a1, inner, 0.06), p(a0, inner, 0.06), p(a0, inner, 0.78), p(a1, inner, 0.78), col)
    box(paint, 0, 1.35, 0, 2.8, 1.15, 2.8, STONE)
    shaft(paint, 1.85, 5.4, 2.15, 1.6, STONE)
    shaft(paint, 5.4, 10.2, 1.6, 1.05, STONE)
    shaft(paint, 10.2, 13.6, 1.05, 0.62, STONE)
    shaft(paint, 13.6, 15.4, 0.7, 0.08, CAP)
    box(paint, 0, 13.15, 0, 0.72, 0.12, 0.72, GOLD)
    lod = Prim()
    box(lod, 0, 7.4, 0, 1.0, 14.4, 1.0, STONE)
    box(lod, 0, 0.4, 0, 9.0, 0.7, 9.0, CHK_W)
    return pack_solid("rb_obelisk", paint, lod)


def build_waves():
    """White wave ribs on the port roundabout, tall enough to clear the palms."""
    paint = Prim()
    disc(paint, 8.0, 0.02, 0.16, GRASS, 22)
    box(paint, 0, 0.48, 0, 3.6, 0.55, 3.6, CHK_W)
    blades = (
        (0.35, 4.8, 7.4, WAVE),
        (1.25, 3.6, 8.8, WAVE2),
        (2.15, 4.4, 6.6, WAVE),
        (2.95, 3.2, 8.0, WAVE2),
        (4.05, 5.0, 6.0, WAVE),
    )
    for yaw, length, crest, col in blades:
        rx, rz = math.cos(yaw), math.sin(yaw)
        nx, nz = -rz, rx
        pts = []
        steps = 16
        for i in range(steps):
            t = i / (steps - 1)
            along = (t - 0.5) * length
            y = math.sin(t * math.pi) ** 1.05 * crest
            lean = math.sin(t * math.pi) * 1.15
            pts.append((rx * along + nx * lean, y + 0.45, rz * along + nz * lean))
        sweep(paint, pts, (nx, nz), 0.26, 0.12, col)
    lod = Prim()
    box(lod, 0, 4.4, 0, 1.4, 8.4, 4.2, WAVE)
    box(lod, 1.2, 3.6, 0, 4.2, 6.6, 1.2, WAVE2)
