def near_clear(x, z, extra=0.0):
    for cx, cz, r in CLEAR:
        if hypot(x - cx, z - cz) < r + extra:
            return True
    return False


def load_named(names, files):
    lines = []
    wanted = tuple(names)
    for fn in files:
        path = REAL / fn
        if not path.exists():
            continue
        data = json.loads(path.read_text())
        for road in data["roads"]:
            name = road.get("n") or ""
            if not name.startswith(wanted):
                continue
            pts = [(p[0], p[1]) for p in road["p"]]
            if len(pts) >= 2:
                lines.append(pts)
    return lines


def chain_lines(lines, gap=16.0):
    """Join road pieces into one southbound polyline."""
    segs = []
    for ln in lines:
        pts = []
        for p in ln:
            if not pts or hypot(p[0] - pts[-1][0], p[1] - pts[-1][1]) > 0.7:
                pts.append((float(p[0]), float(p[1])))
        if len(pts) >= 2:
            segs.append(pts)
    if not segs:
        return []
    segs.sort(key=lambda s: min(s[0][1], s[-1][1]))
    used = [False] * len(segs)
    used[0] = True
    chain = list(segs[0])
    if chain[-1][1] < chain[0][1]:
        chain.reverse()
    guard = 0
    while guard < 200:
        guard += 1
        best = None
        for i, seg in enumerate(segs):
            if used[i]:
                continue
            for rev in (False, True):
                ln = list(reversed(seg)) if rev else seg
                d = hypot(chain[-1][0] - ln[0][0], chain[-1][1] - ln[0][1])
                if best is None or d < best[0]:
                    best = (d, i, ln)
        if best is None or best[0] > gap:
            break
        used[best[1]] = True
        ln = best[2]
        chain.extend(ln[1:] if best[0] < 1.2 else ln)
    # Drop a point that doubles back onto the previous one.
    out = [chain[0]]
    for p in chain[1:]:
        if hypot(p[0] - out[-1][0], p[1] - out[-1][1]) > 0.8:
            out.append(p)
    return out


def walk_chain(chain, step):
    """Samples with a water-side normal. +z is south, water is the low side."""
    if len(chain) < 2:
        return []
    seglen = []
    for i in range(len(chain) - 1):
        seglen.append(hypot(chain[i + 1][0] - chain[i][0], chain[i + 1][1] - chain[i][1]))
    total = sum(seglen)
    samples = []
    dist = 0.0
    prev_n = None
    while dist <= total:
        acc = 0.0
        placed = False
        for i, length in enumerate(seglen):
            if length < 0.5:
                acc += length
                continue
            if acc + length + 1e-6 < dist:
                acc += length
                continue
            t = max(0.0, min(1.0, (dist - acc) / length))
            ax, az = chain[i]
            bx, bz = chain[i + 1]
            x = ax + (bx - ax) * t
            z = az + (bz - az) * t
            tx, tz = (bx - ax) / length, (bz - az) / length
            left = (-tz, tx)
            right = (tz, -tx)
            # Score far enough out that the harbour, not a roadside dip, decides the water side.
            hl = height_at(x + left[0] * 32.0, z + left[1] * 32.0)
            hr = height_at(x + right[0] * 32.0, z + right[1] * 32.0)
            if hl < hr - 0.45:
                n = left
            elif hr < hl - 0.45:
                n = right
            elif prev_n is not None and (prev_n[0] * left[0] + prev_n[1] * left[1]) > 0:
                n = left
            elif prev_n is not None:
                n = right
            else:
                n = left if left[0] <= right[0] else right
            prev_n = n
            samples.append(
                {
                    "x": x,
                    "z": z,
                    "nx": n[0],
                    "nz": n[1],
                    "tx": tx,
                    "tz": tz,
                    "h": height_at(x, z),
                    "s": dist,
                }
            )
            placed = True
            break
        if not placed:
            break
        dist += step
    return samples


def poly_hit(polys, x, z):
    for poly, bb in polys:
        if x < bb[0] or x > bb[1] or z < bb[2] or z > bb[3]:
            continue
        if point_in(poly, x, z):
            return True
    return False


def prep_polys(buildings, extra):
    out = []
    for poly in extra:
        xs = [p[0] for p in poly]
        zs = [p[1] for p in poly]
        out.append((poly, (min(xs), max(xs), min(zs), max(zs))))
    for b in buildings:
        c = b["c"]
        if not (-8300 < c[0] < -6600 and -250 < c[1] < 500):
            continue
        if b["area"] < 20:
            continue
        xs = [p[0] for p in b["poly"]]
        zs = [p[1] for p in b["poly"]]
        out.append((b["poly"], (min(xs), max(xs), min(zs), max(zs))))
    return out


def hero_footprints(ids):
    manifest = json.loads(MANIFEST.read_text())
    polys = []
    found = {}
    for entry in manifest:
        if entry.get("id") not in ids:
            continue
        found[entry["id"]] = entry
        fp = entry.get("hide_footprint")
        if isinstance(fp, list) and len(fp) > 2:
            polys.append(clean_poly([(p[0], p[1]) for p in fp]))
    return polys, found


def loc(p, origin):
    ox, oz, h0 = origin
    return (p[0] - ox, p[1] - h0, p[2] - oz)


def emit_quad(prim, pts, color, prefer):
    """Write one quad whose normal agrees with prefer. Skips zero area."""
    orders = ((0, 1, 2, 3), (1, 0, 3, 2))
    for order in orders:
        a, b, c, d = (pts[i] for i in order)
        n = Prim._n(a, b, c)
        if n is None:
            continue
        if n[0] * prefer[0] + n[1] * prefer[1] + n[2] * prefer[2] >= 0:
            prim.quad(a, b, c, d, color)
            return True
    return False


def ribbon(prim, a, b, c, d, color, origin, prefer):
    """World-space quad a-b-c-d. a,b and d,c are the two edges."""
    if hypot(a[0] - b[0], a[2] - b[2]) < 0.45:
        return
    if hypot(a[0] - d[0], a[2] - d[2]) < 0.15:
        return
    emit_quad(prim, [loc(p, origin) for p in (a, b, c, d)], color, prefer)


