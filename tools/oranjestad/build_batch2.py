def stamp_uv(prim, before, uv, keep_order):
    """UVs for a quad just appended by emit_quad. keep_order matches the source winding."""
    if len(prim.U) < before + 4:
        return
    u0, v0, u1, v1 = uv
    uvs = ((u0, v0), (u1, v0), (u1, v1), (u0, v1))
    order = (0, 1, 2, 3) if keep_order else (1, 0, 3, 2)
    for k, src in enumerate(order):
        prim.U[before + k] = uvs[src]


def banner(atlas, text, slot, bg, fg):
    x, y, w, h = slot
    atlas.draw.rounded_rectangle((x, y, x + w - 1, y + h - 1), radius=16, fill=bg)
    font = atlas.font_lg if len(text) < 14 else atlas.font
    bbox = atlas.draw.textbbox((0, 0), text, font=font)
    tw, th = bbox[2] - bbox[0], bbox[3] - bbox[1]
    atlas.draw.text((x + (w - tw) / 2, y + (h - th) / 2 - 4), text, fill=fg, font=font)
    return atlas._uv(x, y, w, h)


def arcade_on(paint, signs, columns, hero, chain, color, uv, origin, label_h=4.8):
    fp = hero.get("hide_footprint")
    if not isinstance(fp, list) or len(fp) < 4:
        return False
    poly = clean_poly([(p[0], p[1]) for p in fp])
    road = [(s["x"], s["z"]) for s in chain] if chain and isinstance(chain[0], dict) else chain
    edge = street_edge(poly, road)
    if edge is None:
        return False
    _score, _i, a, b, length, outward, dist = edge
    if length < 8 or dist > 40:
        return False
    nx, nz = outward
    dx, dz = (b[0] - a[0]) / length, (b[1] - a[1]) / length
    ground = height_at(*centroid(poly))
    n = max(3, min(16, int(length / 4.0)))
    cols_xy = []
    for k in range(n + 1):
        t = k / n
        px = a[0] + dx * length * t + nx * 1.7
        pz = a[1] + dz * length * t + nz * 1.7
        if poly_hit([], px, pz):
            pass
        gy = height_at(px, pz)
        if gy < 1.0:
            continue
        columns.append(xform(px, gy, pz, origin))
        cols_xy.append((px, pz, gy))
    for i in range(len(cols_xy) - 1):
        ax, az, ah = cols_xy[i]
        bx, bz, bh = cols_xy[i + 1]
        if hypot(ax - bx, az - bz) < 0.8 or hypot(ax - bx, az - bz) > 8:
            continue
        y = max(ah, bh) + 3.22
        ribbon(
            paint,
            (ax, y, az),
            (bx, y, bz),
            (bx + nx * 0.55, y + 0.08, bz + nz * 0.55),
            (ax + nx * 0.55, y + 0.08, az + nz * 0.55),
            TERRACOTTA,
            origin,
            (0, 1, 0),
        )
    if uv and length > 6:
        mid = 0.5
        cx = a[0] + dx * length * mid + nx * 1.9
        cz = a[1] + dz * length * mid + nz * 1.9
        gy = height_at(cx, cz)
        sw, sh = min(8.0, length * 0.45), 1.35
        y0, y1 = gy + label_h, gy + label_h + sh
        s0 = (cx - dx * sw / 2, y0, cz - dz * sw / 2)
        s1 = (cx + dx * sw / 2, y0, cz + dz * sw / 2)
        s2 = (cx + dx * sw / 2 + nx * 0.08, y1, cz + dz * sw / 2 + nz * 0.08)
        s3 = (cx - dx * sw / 2 + nx * 0.08, y1, cz - dz * sw / 2 + nz * 0.08)
        u0, v0, u1, v1 = uv
        before = len(signs.U)
        wrote = emit_quad(
            signs,
            [loc(p, origin) for p in (s0, s1, s2, s3)],
            WHITE,
            (nx, 0, nz),
        )
        if wrote:
            nrm = Prim._n(loc(s0, origin), loc(s1, origin), loc(s2, origin))
            stamp_uv(signs, before, (u0, v0, u1, v1), bool(nrm and nrm[0] * nx + nrm[2] * nz >= 0))
        # The sign faces the roadway, so the camera stands further along the outward normal.
        print(
            f"  cam mallface stand {cx + nx * 14:.0f},{cz + nz * 14:.0f} "
            f"look {cx:.0f},{cz:.0f}"
        )
    return True


