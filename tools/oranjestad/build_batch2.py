def xform(x, y, z, origin, yaw=0.0, scale=1.0):
    ox, oz, h0 = origin
    return (
        (x - ox, y - h0, z - oz),
        yaw_quat(yaw),
        (scale, scale, scale),
    )


def quay_offsets(sample, polys):
    """Return (inner, outer) offsets toward the water, or None."""
    x, z, nx, nz = sample["x"], sample["z"], sample["nx"], sample["nz"]
    if sample["h"] < 1.15:
        return None
    # Stay off the asphalt. The carriageway is already marked with crosswalks.
    inner = 7.2
    hx, hz = x + nx * inner, z + nz * inner
    h_in = height_at(hx, hz)
    if h_in < 1.2 or poly_hit(polys, hx, hz):
        return None
    outer = None
    h_out = h_in
    for dist in (7.6, 9.6, 11.4, 13.2):
        px, pz = x + nx * dist, z + nz * dist
        h = height_at(px, pz)
        if h < 1.15 or abs(h - h_in) > 1.7:
            break
        if poly_hit(polys, px, pz):
            break
        outer = dist
        h_out = h
    if outer is None:
        return None
    return inner, outer, h_in, h_out


def build_quay(samples, polys):
    """Linear Park promenade from the cruise approach to Wilhelmina."""
    keep = []
    for sample in samples:
        if not (-135.0 <= sample["z"] <= 400.0):
            continue
        offsets = quay_offsets(sample, polys)
        if offsets is None:
            continue
        row = dict(sample)
        row["inner"], row["outer"], row["hin"], row["hout"] = offsets
        keep.append(row)
    if len(keep) < 8:
        return None

    ox = sum(s["x"] for s in keep) / len(keep)
    oz = sum(s["z"] for s in keep) / len(keep)
    origin = (ox, oz, height_at(ox, oz))
    paint = Prim()
    lod = Prim()
    palms, lamps, planters, posts = [], [], [], []

    def edge_point(sample, dist, lift):
        y = height_at(sample["x"] + sample["nx"] * dist, sample["z"] + sample["nz"] * dist) + lift
        return (
            sample["x"] + sample["nx"] * dist,
            y,
            sample["z"] + sample["nz"] * dist,
        )

    for i in range(len(keep) - 1):
        a, b = keep[i], keep[i + 1]
        if hypot(a["x"] - b["x"], a["z"] - b["z"]) > 16:
            continue
        brick = BRICK if int(a["s"] / 7) % 2 == 0 else BRICK2
        ribbon(
            paint,
            edge_point(a, a["inner"], 0.07),
            edge_point(b, b["inner"], 0.07),
            edge_point(b, b["outer"], 0.07),
            edge_point(a, a["outer"], 0.07),
            brick,
            origin,
            (0, 1, 0),
        )
        # Low harbour curb. Where the quay drops, the face runs down with it.
        for s0, s1 in ((a, b),):
            y_top = max(s0["hout"], s1["hout"]) + 0.48
            further = height_at(
                s0["x"] + s0["nx"] * (s0["outer"] + 5.0),
                s0["z"] + s0["nz"] * (s0["outer"] + 5.0),
            )
            y_bot = min(s0["hout"], s1["hout"], further + 0.15)
            y_bot = max(y_bot, y_top - 2.1)
            if y_top - y_bot < 0.35:
                y_bot = y_top - 0.42
            o0 = (s0["x"] + s0["nx"] * s0["outer"], s0["z"] + s0["nz"] * s0["outer"])
            o1 = (s1["x"] + s1["nx"] * s1["outer"], s1["z"] + s1["nz"] * s1["outer"])
            thick = 0.24
            t0 = (o0[0] + s0["nx"] * thick, o0[1] + s0["nz"] * thick)
            t1 = (o1[0] + s1["nx"] * thick, o1[1] + s1["nz"] * thick)
            ribbon(
                paint,
                (o0[0], y_top, o0[1]),
                (o1[0], y_top, o1[1]),
                (t1[0], y_top, t1[1]),
                (t0[0], y_top, t0[1]),
                CONCRETE,
                origin,
                (0, 1, 0),
            )
            ribbon(
                paint,
                (t0[0], y_bot, t0[1]),
                (t1[0], y_bot, t1[1]),
                (t1[0], y_top, t1[1]),
                (t0[0], y_top, t0[1]),
                CONCRETE,
                origin,
                (s0["nx"], 0, s0["nz"]),
            )
            # Two white rails.
            for lift in (0.42, 0.78):
                ribbon(
                    paint,
                    (o0[0], s0["hout"] + lift, o0[1]),
                    (o1[0], s1["hout"] + lift, o1[1]),
                    (o1[0] + s1["nx"] * 0.06, s1["hout"] + lift + 0.08, o1[1] + s1["nz"] * 0.06),
                    (o0[0] + s0["nx"] * 0.06, s0["hout"] + lift + 0.08, o0[1] + s0["nz"] * 0.06),
                    WHITE,
                    origin,
                    (s0["nx"], 0.2, s0["nz"]),
                )
        # Far lod: one coarse deck quad.
        if i % 4 == 0 and i + 4 < len(keep):
            c = keep[i + 4]
            if hypot(a["x"] - c["x"], a["z"] - c["z"]) < 40:
                ribbon(
                    lod,
                    edge_point(a, a["inner"], 0.08),
                    edge_point(c, c["inner"], 0.08),
                    edge_point(c, c["outer"], 0.08),
                    edge_point(a, a["outer"], 0.08),
                    BRICK,
                    origin,
                    (0, 1, 0),
                )

    for i, sample in enumerate(keep):
        oxp = sample["x"] + sample["nx"] * sample["outer"]
        ozp = sample["z"] + sample["nz"] * sample["outer"]
        posts.append(xform(oxp, sample["hout"], ozp, origin))
        seaport = -95.0 <= sample["z"] <= 25.0
        if i % 2 == 0 and not seaport and not near_clear(sample["x"], sample["z"]):
            px = sample["x"] + sample["nx"] * (sample["inner"] + 1.3)
            pz = sample["z"] + sample["nz"] * (sample["inner"] + 1.3)
            if not poly_hit(polys, px, pz):
                palms.append(xform(px, height_at(px, pz), pz, origin, scale=0.95 + (i % 3) * 0.06))
        if i % 3 == 0 and not near_clear(sample["x"], sample["z"], 2.0):
            lx = sample["x"] + sample["nx"] * (sample["inner"] + 0.4)
            lz = sample["z"] + sample["nz"] * (sample["inner"] + 0.4)
            if not poly_hit(polys, lx, lz):
                lamps.append(xform(lx, height_at(lx, lz), lz, origin))
        if i % 2 == 1 and 0.0 <= sample["z"] <= 175.0:
            qx = sample["x"] + sample["nx"] * (sample["inner"] - 0.7)
            qz = sample["z"] + sample["nz"] * (sample["inner"] - 0.7)
            if sample["h"] > 1.6 and not poly_hit(polys, qx, qz) and not near_clear(qx, qz):
                planters.append(xform(qx, height_at(qx, qz), qz, origin))

    if paint.tris == 0:
        return None
    glb = Glb("ora_quay")
    glb.mat("paint", rough=0.86)
    glb.add(paint, "paint")
    glb.add_instances(palm_proto(), "paint", palms)
    glb.add_instances(lamp_proto(), "paint", lamps)
    glb.add_instances(planter_proto(), "paint", planters)
    # Posts are a slim white box in the prototype, base at y=0.
    post = Prim()
    box(post, 0, 0.46, 0, 0.1, 0.92, 0.1, WHITE)
    glb.add_instances(post, "paint", posts)
    glb.lod1_prim = lod if lod.tris else None
    print(
        f"quay samples {len(keep)} palms {len(palms)} lamps {len(lamps)} "
        f"planters {len(planters)} posts {len(posts)}"
    )
    for sample in keep:
        if not (100.0 < sample["z"] < 190.0):
            continue
        dist = sample["inner"] + 1.1
        sx = sample["x"] + sample["nx"] * dist
        sz = sample["z"] + sample["nz"] * dist
        if poly_hit(polys, sx, sz) or height_at(sx, sz) < 1.5:
            continue
        lookx = sx + sample["tx"] * 26 + sample["nx"] * 3
        lookz = sz + sample["tz"] * 26 + sample["nz"] * 3
        print(f"  cam promenade stand {sx:.0f},{sz:.0f} look {lookx:.0f},{lookz:.0f}")
        break
    return glb, origin, keep


def build_marina(samples, polys):
    water = []
    for sample in samples:
        if not (40.0 <= sample["z"] <= 250.0):
            continue
        if not (70.0 <= sample["z"] <= 190.0):
            continue
        for dist in (34.0, 40.0, 46.0):
            x = sample["x"] + sample["nx"] * dist
            z = sample["z"] + sample["nz"] * dist
            if height_at(x, z) < 0.2 and not poly_hit(polys, x, z):
                water.append((x, z, sample["tx"], sample["tz"], sample))
                break
    picked = []
    for spot in water:
        if all(hypot(spot[0] - p[0], spot[1] - p[1]) > 18 for p in picked):
            picked.append(spot)
        if len(picked) >= 5:
            break
    if len(picked) < 3:
        print("marina: not enough open water", len(picked))
        return None
    ox = sum(p[0] for p in picked) / len(picked)
    oz = sum(p[1] for p in picked) / len(picked)
    origin = (ox, oz, height_at(ox, oz))
    paint = Prim()
    boats = []
    for i, (x, z, tx, tz, _s) in enumerate(picked):
        yaw = math.atan2(tx, tz) + (0 if i % 2 == 0 else math.pi)
