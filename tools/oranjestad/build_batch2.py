def build_tram(samples, main_road, polys):
    """Shelters only. The track already exists as tramline."""
    stops = []
    # Welcome Plaza, on the inland side of L.G. Smith near the port.
    port = min(samples, key=lambda s: hypot(s["x"] + 7620, s["z"] + 30))
    if hypot(port["x"] + 7620, port["z"] + 30) < 80:
        stops.append(
            (
                port["x"] - port["nx"] * 4.4,
                port["z"] - port["nz"] * 4.4,
                math.atan2(port["tx"], port["tz"]),
            )
        )
    # Schelpstraat / Havenstraat junction on Main Street, then two stops along it.
    for target in ((-7340.0, -8.0), (-7000.0, 22.0), (-6695.0, 56.0)):
        q = closest_on_line(target, main_road)
        # Walk a short step to get a tangent.
        q2 = closest_on_line((target[0] + 6, target[1] + 1), main_road)
        tx, tz = q2[0] - q[0], q2[1] - q[1]
        L = hypot(tx, tz) or 1
        tx, tz = tx / L, tz / L
        # Sidewalk to the north of an east-west street (negative z is north).
        side = 3.8 if tz >= 0 else -3.8
        # left of the tangent is (-tz, tx). Prefer the side with -z.
        left = (-tz, tx)
        if left[1] > 0:
            left = (-left[0], -left[1])
        stops.append((q[0] + left[0] * 3.8, q[1] + left[1] * 3.8, math.atan2(tx, tz)))
    origin_x = sum(s[0] for s in stops) / len(stops)
    origin_z = sum(s[1] for s in stops) / len(stops)
    origin = (origin_x, origin_z, height_at(origin_x, origin_z))
    xforms = []
    for x, z, yaw in stops:
        h = height_at(x, z)
        if poly_hit(polys, x, z):
            print(f"  tram skip inside building {x:.0f},{z:.0f}")
            continue
        if h < 1.2 or near_clear(x, z):
            print(f"  tram skip {x:.0f},{z:.0f} h={h:.2f}")
            continue
        xforms.append(xform(x, h, z, origin, yaw))
        print(f"  tram stop {x:.0f},{z:.0f} h={h:.2f}")
        if abs(x + 7000) < 40:
            print(f"  cam tram-main stand {x + 18:.0f},{z + 6:.0f} look {x:.0f},{z:.0f}")
    if len(xforms) < 2:
        return None
    lod = Prim()
    box(lod, 0, 1.2, 0, 1.4, 2.2, 3.2, WHITE)
    glb = Glb("ora_tramstop")
    glb.mat("paint", rough=0.8)
    glb.add_instances(shelter_proto(), "paint", xforms)
    glb.lod1_prim = lod
    return glb, origin


def build_surfside(chain):
    """Beach dressing plus median palms on L.G. Smith toward the airport.

    Stops west of the airport heroes and short of Plaza di Cultura.
    """
    palms = []
    # Median of the coastal boulevard, z from just south of downtown to ~1160.
    for sample in chain:
        if not (760.0 <= sample["z"] <= 1160.0):
            continue
        if sample["s"] % 48 > 24:
            # walk_chain step is 8; keep every third by index later
            pass
        if sample["h"] < 2.5:
            continue
        if near_clear(sample["x"], sample["z"], 6):
            continue
        if int(sample["s"] / 8) % 3 != 0:
            continue
        # Shoulder, not the travel lane. The coastal road already has its own crosswalks.
        px = sample["x"] + sample["nx"] * 7.5
        pz = sample["z"] + sample["nz"] * 7.5
        hh = height_at(px, pz)
        if hh < 1.4 or near_clear(px, pz, 4):
            continue
        palms.append((px, pz, hh, 0.9))
    # Beach grid. Water is west (lower x); dry sand sits just inland of it.
    umbrellas = []
    step = 7.0
    z = 1325.0
    sand_cells = 0
    while z < 1472.0:
        x = -6540.0
        while x < -6345.0:
            h = height_at(x, z)
            h2 = height_at(x + step, z)
            h3 = height_at(x, z + step)
            h4 = height_at(x + step, z + step)
            heights = (h, h2, h3, h4)
            west = height_at(x - 14, z)
            beach = (
                west + 0.3 < min(heights)
                and all(0.35 <= v <= 3.05 for v in heights)
                and max(heights) - min(heights) < 1.7
            )
            if beach:
                sand_cells += 1
                if sand_cells % 3 == 0:
                    umbrellas.append(((x + x + step) / 2, (z + z + step) / 2, sum(heights) / 4))
                if sand_cells % 4 == 0 and not near_clear(x, z, 2):
                    if all(hypot(x - p[0], z - p[1]) > 11 for p in palms):
                        palms.append((x, z, h, 1.0))
            x += step
        z += step
    # The sand ribbon was stored with origin (0,0,0). Rebuild it once we know
    # the real origin so local Y matches the hero placement.
    if sand_cells < 4 and len(palms) < 4:
        print("surfside: nothing to place", sand_cells, len(palms))
        return None
    ox = -6450.0
    oz = 1280.0
    if palms:
        ox = sum(p[0] for p in palms) / len(palms)
        oz = sum(p[1] for p in palms) / len(palms)
    origin = (ox, oz, height_at(ox, oz))
    # Re-emit sand relative to origin. The earlier ribbon used a dummy origin,
    # so discard it and draw again.
    paint = Prim()
    z = 1325.0
    while z < 1472.0:
        x = -6540.0
        while x < -6345.0:
            h = height_at(x, z)
            h2 = height_at(x + step, z)
            h3 = height_at(x, z + step)
            h4 = height_at(x + step, z + step)
            heights = (h, h2, h3, h4)
            west = height_at(x - 14, z)
            beach = (
                west + 0.3 < min(heights)
                and all(0.35 <= v <= 3.05 for v in heights)
                and max(heights) - min(heights) < 1.7
            )
            if beach:
                ribbon(
                    paint,
                    (x, h + 0.22, z),
                    (x + step, h2 + 0.22, z),
                    (x + step, h4 + 0.22, z + step),
                    (x, h3 + 0.22, z + step),
                    SAND,
                    origin,
                    (0, 1, 0),
                )
            x += step
        z += step
    # A small thatch shade near the sand, clear of the existing bar mesh.
    shade = (-6418.0, 1446.0)
    sh = height_at(*shade)
    if 1.2 < sh < 3.5 and not near_clear(*shade, 2):
        box(paint, shade[0] - ox, (sh + 0.45) - origin[2], shade[1] - oz, 3.2, 0.9, 2.2, WOOD)
        box(paint, shade[0] - ox, (sh + 1.15) - origin[2], shade[1] - oz, 3.6, 0.16, 2.6, (0.72, 0.50, 0.24))
        for sx in (-1.4, 1.4):
            for sz in (-0.9, 0.9):
                box(
                    paint,
                    shade[0] + sx - ox,
                    (sh + 0.7) - origin[2],
                    shade[1] + sz - oz,
                    0.1,
                    1.4,
                    0.1,
                    WOOD,
                )
    lod = Prim()
    box(lod, 0, 0.4, 0, 18, 0.3, 28, SAND)
    glb = Glb("ora_surfside")
    glb.mat("paint", rough=0.9)
    glb.add(paint, "paint")
    palm_xf = [xform(x, h, z, origin, scale=sc) for x, z, h, sc in palms]
    glb.add_instances(palm_proto(), "paint", palm_xf)
    umb = []
    for i, (x, z, h) in enumerate(umbrellas):
        if i % 2:
            continue
        if near_clear(x, z):
            continue
        umb.append(xform(x, h, z, origin, scale=0.9))
        if len(umb) >= 8:
            break
    glb.add_instances(umbrella_proto(), "paint", umb)
    glb.lod1_prim = lod
    print(f"surfside sand-cells ~{sand_cells} palms {len(palms)} umbrellas {len(umb)}")
    # A stand on the sand ribbon, looking west along the beach.
    for x, z, h, _sc in palms:
        if 1360 < z < 1460 and -6500 < x < -6380 and 0.6 < h < 2.4:
            print(f"  cam surfside stand {x + 6:.0f},{z:.0f} look {x - 18:.0f},{z + 12:.0f} h={h:.2f}")
            break
    return glb, origin


def audit(path):
    data = path.read_bytes()
    off = 12
    gltf = None
    blob = None
    while off + 8 <= len(data):
        clen, ctype = struct.unpack_from("<II", data, off)
        off += 8
        chunk = data[off : off + clen]
        off += clen
        if ctype == 0x4E4F534A:
            gltf = json.loads(chunk)
        elif ctype == 0x004E4942:
            blob = chunk
    bad = 0
    nans = 0
    for mesh in gltf["meshes"]:
        for prim in mesh["primitives"]:
            attrs = prim["attributes"]
            pos = read_vec(gltf, blob, attrs["POSITION"], 3)
            nrm = read_vec(gltf, blob, attrs["NORMAL"], 3)
            idx = read_idx(gltf, blob, prim["indices"])
            for n in nrm:
                if any(math.isnan(v) or math.isinf(v) for v in n):
                    nans += 1
                    continue
                L = math.sqrt(n[0] ** 2 + n[1] ** 2 + n[2] ** 2)
                if L < 0.5 or L > 1.5:
                    nans += 1
            for t in range(0, len(idx), 3):
                a, b, c = pos[idx[t]], pos[idx[t + 1]], pos[idx[t + 2]]
                ux, uy, uz = b[0] - a[0], b[1] - a[1], b[2] - a[2]
                vx, vy, vz = c[0] - a[0], c[1] - a[1], c[2] - a[2]
                cx = uy * vz - uz * vy
                cy = uz * vx - ux * vz
                cz = ux * vy - uy * vx
                if math.sqrt(cx * cx + cy * cy + cz * cz) < 1e-6:
                    bad += 1
    print(f"  audit {path.name}: degenerate {bad}, bad normals {nans}")
    return bad + nans


def read_vec(gltf, blob, acc_i, n):
    acc = gltf["accessors"][acc_i]
    view = gltf["bufferViews"][acc["bufferView"]]
    start = view.get("byteOffset", 0) + acc.get("byteOffset", 0)
    count = acc["count"]
    ctype = acc["componentType"]
    if ctype != 5126:
        raise SystemExit(f"unexpected component {ctype}")
    out = []
    for i in range(count):
        out.append(struct.unpack_from("<" + "f" * n, blob, start + i * 4 * n))
    return out


def read_idx(gltf, blob, acc_i):
    acc = gltf["accessors"][acc_i]
    view = gltf["bufferViews"][acc["bufferView"]]
    start = view.get("byteOffset", 0) + acc.get("byteOffset", 0)
    count = acc["count"]
    ctype = acc["componentType"]
    fmt = "<H" if ctype == 5123 else "<I"
    size = 2 if ctype == 5123 else 4
    return [struct.unpack_from(fmt, blob, start + i * size)[0] for i in range(count)]


def save_hero(glb, gid, name, origin, tris_hint, hide, switch, textures):
    glb.name = gid
    data, tris = glb.pack()
    path = HERO / f"{gid}.glb"
    path.write_bytes(data)
    problems = audit(path)
    if problems:
        raise SystemExit(f"{gid} has degenerate geometry")
    entry = manifest_entry(gid, name, origin[0], origin[1], tris, textures, hide, switch)
    entry["status"] = "v5-oranjestad-b2"
    entry["frame"] = FRAME2
    entry["ref_sources"] = REFS2
    entry["geo_source"] = (
        "OSM centre lines (L.G. Smith Boulevard and the downtown side streets) "
        "and building footprints"
    )
    print(f"wrote {path.name} tris {tris} bytes {len(data)}")
    return entry


def save_manifest(entries, retire=()):
    manifest = json.loads(MANIFEST.read_text())
    ids = {e["id"] for e in entries} | set(retire)
    manifest = [e for e in manifest if e.get("id") not in ids]
    manifest.extend(entries)
    text = json.dumps(manifest, indent=1)
    if text.endswith("\n"):
        text = text[:-1]
    MANIFEST.write_text(text)


def clear_side_signs(buildings):
    """Drop floating billboards on side-street shops our facade sign replaces."""
    if not buildings:
        return 0
    raw = LANDMARKS.read_text()
    data = json.loads(raw)
    cleared = 0
    for lm in data:
        x, z = lm.get("x"), lm.get("z")
        if x is None or not lm.get("foot"):
            continue
        for b in buildings:
            if point_in(b["poly"], x, z):
                lm["foot"] = None
                cleared += 1
                break
    if not cleared:
        return 0
    out = json.dumps(data, separators=(",", ":"), ensure_ascii=False)
    # Only accept the write when the rest of the file still round-trips.
    again = json.dumps(json.loads(out), separators=(",", ":"), ensure_ascii=False)
    if again != out:
        print("landmarks round-trip failed; left billboards in place")
        return 0
    LANDMARKS.write_text(out)
    return cleared


