def blockers():
    out = []
    for b in load_buildings():
        c = b["c"]
        if not (-8300 < c[0] < -6800 and -280 < c[1] < 420):
            continue
        poly = b["poly"]
        xs = [p[0] for p in poly]
        zs = [p[1] for p in poly]
        out.append((poly, (min(xs), max(xs), min(zs), max(zs))))
    return out


def inside(polys, x, z):
    for poly, bb in polys:
        if x < bb[0] or x > bb[1] or z < bb[2] or z > bb[3]:
            continue
        if point_in(poly, x, z):
            return True
    return False


def clear_of(polys, x, z):
    best = 1e9
    for poly, bb in polys:
        if x < bb[0] - 18 or x > bb[1] + 18 or z < bb[2] - 18 or z > bb[3] + 18:
            continue
        if point_in(poly, x, z):
            return -1.0
        for i in range(len(poly)):
            a, b = poly[i], poly[(i + 1) % len(poly)]
            abx, abz = b[0] - a[0], b[1] - a[1]
            L2 = abx * abx + abz * abz or 1.0
            t = max(0.0, min(1.0, ((x - a[0]) * abx + (z - a[1]) * abz) / L2))
            d = hypot(x - (a[0] + abx * t), z - (a[1] + abz * t))
            best = min(best, d)
    return best


def hero(gid):
    manifest = json.loads(MANIFEST.read_text())
    entry = next(e for e in manifest if e["id"] == gid)
    poly = clean_poly([(p[0], p[1]) for p in entry["hide_footprint"]])
    return entry, poly


def facing_edge(poly, cam):
    """Long edge whose outward normal points most toward cam."""
    c = centroid(poly)
    best = None
    for i in range(len(poly)):
        a, b = poly[i], poly[(i + 1) % len(poly)]
        L = hypot(b[0] - a[0], b[1] - a[1])
        if L < 3.5:
            continue
        mx, mz = (a[0] + b[0]) / 2, (a[1] + b[1]) / 2
        outward = norm((mx - c[0], mz - c[1]))
        toward = norm((cam[0] - mx, cam[1] - mz))
        score = outward[0] * toward[0] + outward[1] * toward[1]
        key = score + min(L, 22.0) * 0.012
        if score > 0.25 and (best is None or key > best[0]):
            best = (key, a, b, outward, L, score)
    if best is None:
        raise SystemExit("no camera-facing edge")
    return best


def front_ground(a, b):
    vals = []
    for t in (0.25, 0.5, 0.75):
        vals.append(height_at(a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t))
    return max(vals)


def tri_up(prim, a, b, c, color):
    n = Prim._n(a, b, c)
    if n is None:
        return
    if n[1] < 0:
        prim.tri(a, c, b, color)
    else:
        prim.tri(a, b, c, color)


def quad_out(prim, p0, p1, p2, p3, color, prefer):
    n = Prim._n(p0, p1, p2)
    if n is None:
        return
    if n[0] * prefer[0] + n[1] * prefer[1] + n[2] * prefer[2] >= 0:
        prim.quad(p0, p1, p2, p3, color)
    else:
        prim.quad(p1, p0, p3, p2, color)


def tri_out(prim, a, b, c, color, prefer):
    n = Prim._n(a, b, c)
    if n is None:
        return
    if n[0] * prefer[0] + n[1] * prefer[1] + n[2] * prefer[2] >= 0:
        prim.tri(a, b, c, color)
    else:
        prim.tri(a, c, b, color)


def edge_basis(a, b):
    dx, dz = b[0] - a[0], b[1] - a[1]
    L = hypot(dx, dz) or 1.0
    return dx / L, dz / L, L


def world(origin, h0, x, y, z):
    return (x - origin[0], y - h0, z - origin[1])


def span_quad(prim, a, b, outward, t0, t1, y0, y1, color, origin, h0, proud, prefer=None):
    tx, tz, L = edge_basis(a, b)
    t0 = max(0.15, min(L - 0.15, t0))
    t1 = max(0.15, min(L - 0.15, t1))
    if t1 - t0 < 0.25 or y1 - y0 < 0.12:
        return
    nx, nz = outward
    ox, oz = origin

    def p(t, y):
        return (
            a[0] + tx * t + nx * proud - ox,
            y - h0,
            a[1] + tz * t + nz * proud - oz,
        )

    prefer = prefer or (nx, 0.0, nz)
    quad_out(prim, p(t0, y0), p(t1, y0), p(t1, y1), p(t0, y1), color, prefer)


def hip_roof(prim, poly, origin, h0, y_eave, rise, color):
    c = centroid(poly)
    peak = (c[0] - origin[0], y_eave + rise - h0, c[1] - origin[1])
    for i in range(len(poly)):
        p, q = poly[i], poly[(i + 1) % len(poly)]
        tri_up(
            prim,
            peak,
            (p[0] - origin[0], y_eave - h0, p[1] - origin[1]),
            (q[0] - origin[0], y_eave - h0, q[1] - origin[1]),
            color,
        )


def opening(prim, a, b, outward, t, y0, y1, w, origin, h0, body, frame, glass, shutter=None):
    """A window or door in the wall plane. t is the centre, in metres."""
    span_quad(prim, a, b, outward, t - w * 0.62, t + w * 0.62, y0 - 0.08, y1 + 0.08, frame, origin, h0, 0.05)
    span_quad(prim, a, b, outward, t - w * 0.5, t + w * 0.5, y0, y1, glass, origin, h0, 0.09)
    if shutter:
        span_quad(prim, a, b, outward, t - w * 1.05, t - w * 0.48, y0, y1, shutter, origin, h0, 0.1)
        span_quad(prim, a, b, outward, t + w * 0.48, t + w * 1.05, y0, y1, shutter, origin, h0, 0.1)
    # Shallow arch above the opening.
    tx, tz, _L = edge_basis(a, b)
    nx, nz = outward
    ox, oz = origin
    r = w * 0.5
    cx = a[0] + tx * t + nx * 0.09
    cz = a[1] + tz * t + nz * 0.09
    spring = y1
    left = (
        cx - tx * r - ox,
        spring - h0,
        cz - tz * r - oz,
    )
    steps = 4
    prev = left
    crown = (cx - ox, spring - h0, cz - oz)
    for i in range(1, steps + 1):
        ang = math.pi - i / steps * math.pi
        nxt = (
            cx + math.cos(ang) * r * tx - ox,
            spring + math.sin(ang) * r * 0.85 - h0,
            cz + math.cos(ang) * r * tz - oz,
        )
        tri_out(prim, crown, prev, nxt, frame, (nx, 0.25, nz))
        prev = nxt


def windows_on(prim, a, b, outward, ground, origin, h0, floors, shutter=None, skip_ground=False):
    _tx, _tz, L = edge_basis(a, b)
    if L < 7.0:
        return
    margin = 1.6
    usable = L - margin * 2
    gap = 2.55
    n = max(1, int(usable / gap))
    for floor, (y0, y1, w) in enumerate(floors):
        if skip_ground and floor == 0:
            continue
        for k in range(n):
            t = margin + (k + 0.5) * (L - margin * 2) / n
            opening(prim, a, b, outward, t, ground + y0, ground + y1, w, origin, h0, None, TRIM, GLASS, shutter)


def cornice(prim, poly, origin, h0, y, color):
    c = centroid(poly)
    for i in range(len(poly)):
        a, b = poly[i], poly[(i + 1) % len(poly)]
        L = hypot(b[0] - a[0], b[1] - a[1])
        if L < 1.2:
            continue
        mx, mz = (a[0] + b[0]) / 2, (a[1] + b[1]) / 2
        outward = norm((mx - c[0], mz - c[1]))
        span_quad(prim, a, b, outward, 0.2, L - 0.2, y - 0.32, y + 0.06, color, origin, h0, 0.16)


def flag_quad(signs, atlas_uv, x, y, z, origin, h0, nx, nz):
    ox, oz = origin
    u0, v0, u1, v1 = atlas_uv
    w, h = 1.7, 1.05
    # Flag hangs to the right of the pole, facing the camera normal.
    p0 = (x + nz * 0.05 - ox, y - h0, z - nx * 0.05 - oz)
    p1 = (x + nx * w + nz * 0.05 - ox, y - h0, z + nz * w - nx * 0.05 - oz)
    p2 = (x + nx * w + nz * 0.05 - ox, y + h - h0, z + nz * w - nx * 0.05 - oz)
    p3 = (x + nz * 0.05 - ox, y + h - h0, z - nx * 0.05 - oz)
    signs.quad(p0, p1, p2, p3, (1, 1, 1), ((u0, v0), (u1, v0), (u1, v1), (u0, v1)))


def sign_quad(signs, uv, a, b, outward, t0, t1, y0, y1, origin, h0, proud=0.18):
    tx, tz, _L = edge_basis(a, b)
    nx, nz = outward
    ox, oz = origin
    u0, v0, u1, v1 = uv

    def p(t, y):
        return (
            a[0] + tx * t + nx * proud - ox,
            y - h0,
            a[1] + tz * t + nz * proud - oz,
        )

    p0, p1, p2, p3 = p(t0, y0), p(t1, y0), p(t1, y1), p(t0, y1)
    n = Prim._n(p0, p1, p2)
    order = (p0, p1, p2, p3)
    uvs = ((u0, v0), (u1, v0), (u1, v1), (u0, v1))
    if n is not None and n[0] * nx + n[2] * nz < 0:
        order = (p1, p0, p3, p2)
        uvs = ((u1, v0), (u0, v0), (u0, v1), (u1, v1))
    signs.quad(*order, (1, 1, 1), uvs)


def street_gable(paint, a, b, outward, y_eave, rise, origin, h0, color):
    """A roof triangle on the street face, tall enough to clear the wall from the sidewalk."""
    tx, tz, L = edge_basis(a, b)
    t0, t1 = L * 0.12, L * 0.88
    tm = (t0 + t1) / 2
    ox, oz = origin
    nx, nz = outward

    def at(t, y):
        return (a[0] + tx * t + nx * 0.22 - ox, y - h0, a[1] + tz * t + nz * 0.22 - oz)

    tri_out(paint, at(t0, y_eave), at(t1, y_eave), at(tm, y_eave + rise), color, (nx, 0.45, nz))


def paint_sign(atlas, text, bg, fg):
    x, y, w, h = 16, 16, 760, 150
    atlas.draw.rectangle((x, y, x + w - 1, y + h - 1), fill=bg)
    atlas.draw.rectangle((x + 8, y + 8, x + w - 9, y + h - 9), outline=fg, width=6)
    font = atlas.font_lg if len(text) < 14 else atlas.font
    bbox = atlas.draw.textbbox((0, 0), text, font=font)
    tw, th = bbox[2] - bbox[0], bbox[3] - bbox[1]
    atlas.draw.text((x + (w - tw) / 2, y + (h - th) / 2 - 6), text, fill=fg, font=font)
    return atlas._uv(x, y, w, h)


def portico(paint, signs, a, b, outward, ground, origin, h0, uv_flag, uv_sign):
    tx, tz, L = edge_basis(a, b)
    nx, nz = outward
    ox, oz = origin
    inset = min(2.2, L * 0.12)
    span = L - inset * 2
    cols = 4
    base = ground
    shaft = 4.7
    for k in range(cols):
        t = inset + span * (k + 0.5) / cols
        cx = a[0] + tx * t + nx * 1.7
        cz = a[1] + tz * t + nz * 1.7
        cyl(paint, cx - ox, base - h0, cz - oz, 0.28, shaft, TRIM, seg=6)
        cyl(paint, cx - ox, base + shaft - h0, cz - oz, 0.38, 0.16, TRIM, seg=6)
    # Entablature, a beam in front of the wall.
    t0, t1 = inset * 0.7, L - inset * 0.7
    yb0, yb1 = base + shaft + 0.12, base + shaft + 0.62
    span_quad(paint, a, b, outward, t0, t1, yb0, yb1, TRIM, origin, h0, 2.15)
    span_quad(paint, a, b, outward, t0, t1, yb0, yb1, TRIM, origin, h0, 0.35)
    # Pediment.
    tm = (t0 + t1) / 2
    peak_y = yb1 + 1.85

    def at(t, y, proud):
        return (
            a[0] + tx * t + nx * proud - ox,
            y - h0,
            a[1] + tz * t + nz * proud - oz,
        )

    for proud in (2.15, 0.4):
        p0, p1, p2 = at(t0, yb1, proud), at(t1, yb1, proud), at(tm, peak_y, proud)
        tri_out(paint, p0, p1, p2, TRIM, (nx, 0.35, nz))
    # Door in the centre of the porch.
    opening(paint, a, b, outward, L * 0.5, base + 0.15, base + 2.7, 1.35, origin, h0, None, TRIM, (0.22, 0.14, 0.09))
    if uv_sign:
        sign_quad(signs, uv_sign, a, b, outward, L * 0.5 - 2.6, L * 0.5 + 2.6, yb0 + 0.05, yb1 - 0.05, origin, h0, 2.22)
    if uv_flag:
        fx = a[0] + tx * tm + nx * 2.3
        fz = a[1] + tz * tm + nz * 2.3
        cyl(paint, fx - ox, peak_y - h0, fz - oz, 0.05, 2.4, TRIM, seg=5)
        flag_quad(signs, uv_flag, fx, peak_y + 1.15, fz, origin, h0, nx, nz)


def colonial(gid, filename, cam, wall, floors, eave_h, roof_rise, shutter=None, porch="none", sign=None, sign_bg=(245, 240, 226), sign_fg=(28, 18, 12)):
    entry, poly = hero(gid)
    ox, oz = entry["x"], entry["z"]
    h0 = height_at(ox, oz)
    _key, a, b, outward, L, score = facing_edge(poly, cam)
    ground = front_ground(a, b)
    print(f"{gid} front {L:.1f}m face {score:.2f} ground {ground:.2f} h0 {h0:.2f}")
    paint, signs = Prim(), Prim()
    extrude_walls(paint, poly, ground - 0.4, ground + eave_h, wall, (ox, oz), h0)
    hip_roof(paint, poly, (ox, oz), h0, ground + eave_h, roof_rise, ROOF)
    cornice(paint, poly, (ox, oz), h0, ground + eave_h, TRIM)
    c = centroid(poly)
    atlas = Atlas()
    uv_sign = paint_sign(atlas, sign, sign_bg, sign_fg) if sign else None
    uv_flag = atlas.flag()
    for i in range(len(poly)):
        ea, eb = poly[i], poly[(i + 1) % len(poly)]
        el = hypot(eb[0] - ea[0], eb[1] - ea[1])
        if el < 6.5:
            continue
        mx, mz = (ea[0] + eb[0]) / 2, (ea[1] + eb[1]) / 2
        out = norm((mx - c[0], mz - c[1]))
        same = hypot(ea[0] - a[0], ea[1] - a[1]) < 0.2 and hypot(eb[0] - b[0], eb[1] - b[1]) < 0.2
        if same and porch in ("columns", "canopy"):
            continue
        windows_on(
            paint,
            ea,
            eb,
            out,
            ground,
            (ox, oz),
            h0,
            floors,
            shutter,
        )
    if porch == "columns":
        portico(paint, signs, a, b, outward, ground, (ox, oz), h0, uv_flag, uv_sign)
        # Hip peak sits behind the eave from the sidewalk. The triangle is on the
        # wall, behind the white pediment, so the red roof clears the portico.
        street_gable(paint, a, b, outward, ground + eave_h, 3.6, (ox, oz), h0, ROOF)
    elif porch == "canopy":
        tx, tz, _el = edge_basis(a, b)
        nx, nz = outward
        span_quad(paint, a, b, outward, L * 0.28, L * 0.72, ground + 3.15, ground + 3.4, TRIM, (ox, oz), h0, 1.7)
        for t in (L * 0.34, L * 0.66):
            cx = a[0] + tx * t + nx * 1.45
            cz = a[1] + tz * t + nz * 1.45
            cyl(paint, cx - ox, ground - h0, cz - oz, 0.16, 3.2, TRIM, seg=6)
        opening(paint, a, b, outward, L * 0.5, ground + 0.15, ground + 2.5, 1.2, (ox, oz), h0, None, TRIM, (0.22, 0.14, 0.09))
        if uv_sign:
            sign_quad(signs, uv_sign, a, b, outward, L * 0.5 - 2.3, L * 0.5 + 2.3, ground + 3.5, ground + 4.15, (ox, oz), h0, 0.2)
        fx = a[0] + tx * L * 0.82 + nx * 0.4
        fz = a[1] + tz * L * 0.82 + nz * 0.4
        cyl(paint, fx - ox, ground + eave_h - h0, fz - oz, 0.05, 2.2, TRIM, seg=5)
        flag_quad(signs, uv_flag, fx, ground + eave_h + 1.3, fz, (ox, oz), h0, nx, nz)
        street_gable(paint, a, b, outward, ground + eave_h, 3.2, (ox, oz), h0, ROOF)
    else:
        tx, tz, _el = edge_basis(a, b)
        nx, nz = outward
        if uv_sign:
            sign_quad(signs, uv_sign, a, b, outward, L * 0.5 - 2.4, L * 0.5 + 2.4, ground + eave_h - 1.15, ground + eave_h - 0.45, (ox, oz), h0)
        fx = a[0] + tx * (L * 0.82) + nx * 0.35
        fz = a[1] + tz * (L * 0.82) + nz * 0.35
        cyl(paint, fx - ox, ground + eave_h - h0, fz - oz, 0.05, 2.1, TRIM, seg=5)
        flag_quad(signs, uv_flag, fx, ground + eave_h + 1.2, fz, (ox, oz), h0, nx, nz)
    if porch != "columns":
        street_gable(paint, a, b, outward, ground + eave_h, 3.4, (ox, oz), h0, ROOF)
    lod = Prim()
    extrude_walls(lod, poly, ground - 0.4, ground + eave_h + roof_rise * 0.5, wall, (ox, oz), h0)
    glb = Glb(gid)
    glb.mat("paint", rough=0.84)
    glb.mat("sign", rough=0.6, tex=0, double=True)
    glb.images.append((atlas.png(), "image/png"))
    glb.add(paint, "paint")
    glb.add(signs, "sign")
    glb.lod1_prim = lod
    return glb, (ox, oz, h0)


def wave_roof(paint, a, b, inward, origin, h0, y_eave, depth, color):
    """Two waves whose front edge stands above the land wall."""
    tx, tz, L = edge_basis(a, b)
    ix, iz = inward
    ox, oz = origin
    n = 10
    outward = (-ix, 0.15, -iz)

    def at(t, s, y):
        return (a[0] + tx * t + ix * s - ox, y - h0, a[1] + tz * t + iz * s - oz)

    for k in range(n):
        t0 = L * k / n
        t1 = L * (k + 1) / n
        h0s = 0.55 + 2.7 * abs(math.sin(k / n * math.tau))
        h1s = 0.55 + 2.7 * abs(math.sin((k + 1) / n * math.tau))
        quad_out(
            paint,
            at(t0, 0.4, y_eave),
            at(t1, 0.4, y_eave),
            at(t1, 0.4, y_eave + h1s),
            at(t0, 0.4, y_eave + h0s),
            color,
            outward,
        )
        tri_up(paint, at(t0, 0.4, y_eave + h0s), at(t1, 0.4, y_eave + h1s), at(t1, depth * 0.55, y_eave + 0.25), color)
        tri_up(paint, at(t0, 0.4, y_eave + h0s), at(t1, depth * 0.55, y_eave + 0.25), at(t0, depth * 0.55, y_eave + 0.25), color)


