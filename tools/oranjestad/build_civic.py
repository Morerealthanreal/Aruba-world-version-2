def deck(paint, x0, z0, x1, z1, half_w, y, origin, h0, color):
    dx, dz = x1 - x0, z1 - z0
    L = hypot(dx, dz) or 1.0
    px, pz = -dz / L * half_w, dx / L * half_w
    ox, oz = origin
    a = (x0 - px, y, z0 - pz)
    b = (x1 - px, y, z1 - pz)
    c = (x1 + px, y, z1 + pz)
    d = (x0 + px, y, z0 + pz)

    def loc(p):
        return (p[0] - ox, p[1] - h0, p[2] - oz)

    tri_up(paint, loc(a), loc(b), loc(c), color)
    tri_up(paint, loc(a), loc(c), loc(d), color)
    # Side faces so the deck has thickness over the water.
    yb = y - 0.28
    for p, q in ((a, b), (c, d)):
        quad_out(
            paint,
            loc((p[0], yb, p[2])),
            loc((q[0], yb, q[2])),
            loc((q[0], y, q[2])),
            loc((p[0], y, p[2])),
            WOOD2,
            (q[0] - p[0], 0, q[2] - p[2]),
        )


def find_run(polys, z, want, span=22):
    """Beach point, then enough open water for a pier."""
    start = None
    for x in range(-7368, -7560, -2):
        if inside(polys, x, z):
            continue
        h = height_at(x, z)
        if start is None and 0.55 < h < 1.7 and clear_of(polys, x, z) > 1.0:
            start = (x, z, h)
            continue
        if start and start[0] - x >= span and h < 0.35:
            return start, (x, z, h)
    return None


def choose_pier(polys, z0, z1, target, span=22):
    best = None
    for z in range(z0, z1, 2):
        run = find_run(polys, z, target, span)
        if not run:
            continue
        start, end = run
        mx = (start[0] + end[0]) / 2
        d = hypot(mx - target[0], z - target[1])
        if best is None or d < best[0]:
            best = (d, start, end, start[0] - end[0])
    if best is None:
        raise SystemExit(f"no pier near {target}")
    print(f"pier z {best[1][1]} span {best[3]:.0f}m start {best[1][0]:.0f} end {best[2][0]:.0f} dist {best[0]:.0f}")
    return best[1], best[2]


def build_marina(polys):
    start, end = choose_pier(polys, 150, 164, (-7460.0, 156.0), span=28)
    x0, z0 = start[0], start[1]
    x1, z1 = end[0], end[1]
    ox, oz = (x0 + x1) / 2, (z0 + z1) / 2
    h0 = height_at(ox, oz)
    origin = (ox, oz, h0)
    paint = Prim()
    y = 0.72
    deck(paint, x0, z0, x1, z1, 1.35, y, (ox, oz), h0, WOOD)
    dx, dz = x1 - x0, z1 - z0
    L = hypot(dx, dz) or 1.0
    tx, tz = dx / L, dz / L
    # The marina camera stands south of this pier. Fingers and yachts
    # sit on that near side so the hulls are not hidden behind the deck.
    near = 1.0 if z0 < 168 else -1.0
    for t in (0.3, 0.52, 0.74):
        px = x0 + tx * L * t
        pz = z0 + tz * L * t
        deck(paint, px, pz, px, pz + near * 9.0, 0.95, y, (ox, oz), h0, WOOD)
        deck(paint, px, pz, px, pz - near * 6.0, 0.85, y, (ox, oz), h0, WOOD2)
    for t in (0.18, 0.4, 0.62, 0.84):
        px = x0 + tx * L * t
        pz = z0 + tz * L * t
        cyl(paint, px - ox, -0.15 - h0, pz - oz, 0.18, y + 0.4, WOOD2, seg=5)
    spots = []
    for i, t in enumerate((0.34, 0.52, 0.7, 0.86)):
        px = x0 + (x1 - x0) * t
        pz = z0 + near * (8.0 if i % 2 == 0 else 12.5)
        if height_at(px, pz) < 0.9 and not inside(polys, px, pz):
            spots.append((px, pz, i))
    for i, extra in enumerate((6.0, 12.0)):
        px = x1 - 4.0
        pz = z0 + near * extra
        if height_at(px, pz) < 0.6 and not inside(polys, px, pz):
            spots.append((px, pz, 10 + i))
    yaw = 0.0
    yachts, tenders = [], []
    for px, pz, i in spots:
        side = yaw if i % 2 == 0 else yaw + math.pi
        if i >= 10 or i % 2 == 0:
            yachts.append(xform(px, SEA_Y, pz, origin, side, 1.05))
        else:
            tenders.append(xform(px, SEA_Y, pz, origin, side, 0.86))
    print(f"marina yachts {len(yachts)} tenders {len(tenders)} spots {[(round(p[0]), round(p[1])) for p in spots]}")
    lod = Prim()
    box(lod, 0, 0.4 - h0, 0, 8, 1.2, 16, HULL)
    glb = Glb("ora_marina")
    glb.mat("paint", rough=0.74)
    glb.add(paint, "paint")
    glb.add_instances(yacht_proto(), "paint", yachts)
    glb.add_instances(tender_proto(), "paint", tenders)
    glb.lod1_prim = lod
    return glb, origin


def build_ferry(polys):
    start, end = choose_pier(polys, 160, 176, (-7422.0, 170.0), span=24)
    x0, z0 = start[0] - 2.0, start[1]
    x1, z1 = end[0] - 4.0, end[1]
