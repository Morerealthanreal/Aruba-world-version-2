    deck(paint, x0, z0, x1, z1, 1.7, y, (ox, oz), h0, (0.62, 0.60, 0.56))
    # White canopy with a blue fascia.
    tx, tz, _L = 1.0, 0.0, abs(x1 - x0)
    L = abs(x1 - x0)
    canopy_y = y + 3.05
    for s0, s1 in ((0.15, 0.92),):
        ax, bx = x0 + (x1 - x0) * s0, x0 + (x1 - x0) * s1
        deck(paint, ax, z0, bx, z1, 2.05, canopy_y, (ox, oz), h0, TRIM)
        # Blue edge band.
        deck(paint, ax, z0 - 1.7, bx, z0 - 1.7, 0.18, canopy_y + 0.12, (ox, oz), h0, BLUE)
    for t in (0.22, 0.45, 0.68, 0.88):
        px = x0 + (x1 - x0) * t
        for side in (-1.45, 1.45):
            cyl(paint, px - ox, y - 0.2 - h0, z0 + side - oz, 0.1, 3.15, TRIM, seg=5)
