def shop_name(b, landmarks):
    name = (b.get("n") or "").strip()
    if name:
        return name
    cx, cz = b["c"]
    for lm in landmarks:
        x, z = lm.get("x"), lm.get("z")
        if x is None or abs(x - cx) > 40 or abs(z - cz) > 40:
            continue
        if point_in(b["poly"], x, z):
            return (lm.get("name") or "").strip()
    return ""


def select_mainstreet(buildings, road, blockers, landmarks):
    picked = []
    for b in buildings:
        c = b["c"]
        if not (-7600 < c[0] < -6550 and -80 < c[1] < 160):
            continue
        # Warehouses and mall masses stay as the existing heroes / OSM blocks.
        if b["area"] < 28 or b["area"] > 420:
            continue
        if b.get("k") in ("hotel", "church", "ind"):
            continue
        if height_at(*c) < 1.0:
            continue
        d = min_dist_to_poly(c, road)
        if d > 26:
            continue
        if blocked(b, *blockers):
            continue
        edge = street_edge(b["poly"], road)
        if edge is None or edge[5] is None or edge[6] > 22:
            continue
        # only the street wall that actually faces the pedestrian way
        if edge[4] < 3.2:
            continue
        name = shop_name(b, landmarks)
        low = name.lower()
        if "bazaar" in low or "renaissance mall" in low or "royal plaza" in low:
            continue
        col = PASTELS[int(hash01(b.get("i") or 1, 2) * len(PASTELS)) % len(PASTELS)]
        if "penha" in low:
            col = (0.95, 0.82, 0.28)
        b2 = dict(b)
        b2["color"] = col
        b2["edge"] = edge
        b2["sign_name"] = name
        picked.append(b2)
    # Neighbours alternate stepped / neck / pediment so a close-up row is
    # three different skylines, not one repeated curve.
    picked.sort(key=lambda b: (round(b["c"][0], 1), round(b["c"][1], 1)))
    for i, b2 in enumerate(picked):
        b2["gable"] = i % 3
    return picked


def chunk_buildings(picked):
    # three bands along the street (west to east, x more negative = west)
    bands = [(-8000, -7150), (-7150, -6850), (-6850, -6400)]
    groups = [[] for _ in bands]
    for b in picked:
        x = b["c"][0]
        for i, (a, c) in enumerate(bands):
            if a <= x < c:
                groups[i].append(b)
                break
    return [g for g in groups if g]


