def build_facade(prim, glass, b, edge, origin, h0, uv, kind):
    poly = b["poly"]
    score, i, a, bb, L, outward, dist = edge
    ground = height_at(*b["c"])
    eave = ground + 6.35
    # side and back walls to the eave; street wall slightly shorter so the
    # parapet reads as the front
    extrude_walls(prim, poly, ground, eave, b["color"], origin, h0)
    # roof cap, slightly inset colour
    c = centroid(poly)
    ox, oz = origin
    roof_y = eave - 0.05
    # fan from centroid
    for i2 in range(len(poly)):
        p, q = poly[i2], poly[(i2 + 1) % len(poly)]
        peak = (c[0] - ox, roof_y - h0 + 0.55, c[1] - oz)
        e0 = (p[0] - ox, roof_y - h0, p[1] - oz)
        e1 = (q[0] - ox, roof_y - h0, q[1] - oz)
        ux, uy, uz = e1[0] - peak[0], e1[1] - peak[1], e1[2] - peak[2]
        vx, vy, vz = e0[0] - peak[0], e0[1] - peak[1], e0[2] - peak[2]
        ny = uz * vx - ux * vz
        if ny >= 0:
            prim.tri(peak, e1, e0, TERRACOTTA)
        else:
            prim.tri(peak, e0, e1, TERRACOTTA)
    parapet(prim, a, bb, outward, eave, b["color"], WHITE, origin, h0, kind, scale=1.0)
    # white cornice along the street
    nx, nz = outward
    dx, dz = bb[0] - a[0], bb[1] - a[1]
    tx, tz = dx / (L or 1), dz / (L or 1)
    cornice_y = eave - h0
    p0 = (a[0] + nx * 0.16 - ox, cornice_y, a[1] + nz * 0.16 - oz)
    p1 = (bb[0] + nx * 0.16 - ox, cornice_y, bb[1] + nz * 0.16 - oz)
    p2 = (bb[0] + nx * 0.16 - ox, cornice_y + 0.22, bb[1] + nz * 0.16 - oz)
    p3 = (a[0] + nx * 0.16 - ox, cornice_y + 0.22, a[1] + nz * 0.16 - oz)
    # p0->p1->p2 normal is (-tz, tx), the street side of a clockwise footprint.
    face_out = (-tz) * nx + tx * nz >= 0
    if face_out:
        prim.quad(p0, p1, p2, p3, WHITE)
    else:
        prim.quad(p1, p0, p3, p2, WHITE)
    # shopfront glass, facing the street
    gy0 = ground + 0.35 - h0
    gy1 = ground + 2.75 - h0
    margin = min(1.1, L * 0.12)
    g0 = (a[0] + tx * margin + nx * 0.08 - ox, gy0, a[1] + tz * margin + nz * 0.08 - oz)
    g1 = (bb[0] - tx * margin + nx * 0.08 - ox, gy0, bb[1] - tz * margin + nz * 0.08 - oz)
    g2 = (bb[0] - tx * margin + nx * 0.08 - ox, gy1, bb[1] - tz * margin + nz * 0.08 - oz)
    g3 = (a[0] + tx * margin + nx * 0.08 - ox, gy1, a[1] + tz * margin + nz * 0.08 - oz)
    if face_out:
        glass.quad(g0, g1, g2, g3, (0.16, 0.24, 0.30))
    else:
        glass.quad(g1, g0, g3, g2, (0.16, 0.24, 0.30))
    # door at the left end of the front
    dw = min(1.0, L * 0.18)
    d0 = (a[0] + tx * 0.35 + nx * 0.1 - ox, ground - h0, a[1] + tz * 0.35 + nz * 0.1 - oz)
    d1 = (a[0] + tx * (0.35 + dw) + nx * 0.1 - ox, ground - h0, a[1] + tz * (0.35 + dw) + nz * 0.1 - oz)
    d2 = (a[0] + tx * (0.35 + dw) + nx * 0.1 - ox, ground + 2.35 - h0, a[1] + tz * (0.35 + dw) + nz * 0.1 - oz)
    d3 = (a[0] + tx * 0.35 + nx * 0.1 - ox, ground + 2.35 - h0, a[1] + tz * 0.35 + nz * 0.1 - oz)
    if face_out:
        prim.quad(d0, d1, d2, d3, DOOR)
    else:
        prim.quad(d1, d0, d3, d2, DOOR)
    # sign board
    sw = min(L * 0.62, 7.2)
    if sw > 1.6 and uv:
        sm = (L - sw) / 2
        sy0 = ground + 2.95 - h0
        sy1 = ground + 3.62 - h0
        s0 = (a[0] + tx * sm + nx * 0.14 - ox, sy0, a[1] + tz * sm + nz * 0.14 - oz)
        s1 = (a[0] + tx * (sm + sw) + nx * 0.14 - ox, sy0, a[1] + tz * (sm + sw) + nz * 0.14 - oz)
        s2 = (a[0] + tx * (sm + sw) + nx * 0.14 - ox, sy1, a[1] + tz * (sm + sw) + nz * 0.14 - oz)
        s3 = (a[0] + tx * sm + nx * 0.14 - ox, sy1, a[1] + tz * sm + nz * 0.14 - oz)
        u0, v0, u1, v1 = uv
        # return the quad via a side channel: paint it here if prim is the sign prim
        return (s0, s1, s2, s3, (u0, v0), (u1, v0), (u1, v1), (u0, v1), face_out, ground, outward, a, bb, L)
    return None


