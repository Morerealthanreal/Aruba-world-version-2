def height_at(x, z, cache={}):
    rx = int((x - X0) // RS)
    rz = int((z - Z0) // RS)
    key = (rx, rz)
    if key not in cache:
        im = Image.open(REAL / f"h_{rx}_{rz}.png").convert("RGB")
        cache[key] = (im, im.load(), im.size)
    im, px, (w, h) = cache[key]
    u = (x - (X0 + rx * RS)) / RS
    v = (z - (Z0 + rz * RS)) / RS
    fx = min(w - 1.001, max(0.0, u * (w - 1)))
    fy = min(h - 1.001, max(0.0, v * (h - 1)))
    x0, y0 = int(fx), int(fy)
    x1, y1 = min(w - 1, x0 + 1), min(h - 1, y0 + 1)
    tx, ty = fx - x0, fy - y0

    def H(ix, iy):
        r, g, b = px[ix, iy]
        return (r * 256 + g) / 100 - 50

    return (
        H(x0, y0) * (1 - tx) * (1 - ty)
        + H(x1, y0) * tx * (1 - ty)
        + H(x0, y1) * (1 - tx) * ty
        + H(x1, y1) * tx * ty
    )


def hypot(x, z):
    return math.hypot(x, z)


def sub(a, b):
    return (a[0] - b[0], a[1] - b[1])


def add(a, b):
    return (a[0] + b[0], a[1] + b[1])


def mul(a, s):
    return (a[0] * s, a[1] * s)


def dot(a, b):
    return a[0] * b[0] + a[1] * b[1]


def norm(a):
    L = hypot(a[0], a[1]) or 1
    return (a[0] / L, a[1] / L)


def dist_point_seg(p, a, b):
    ab = sub(b, a)
    L2 = dot(ab, ab) or 1
    t = max(0.0, min(1.0, dot(sub(p, a), ab) / L2))
    q = add(a, mul(ab, t))
    return hypot(p[0] - q[0], p[1] - q[1]), q, t


def poly_area(poly):
    a = 0.0
    for i in range(len(poly)):
        x, z = poly[i]
        x2, z2 = poly[(i + 1) % len(poly)]
        a += x * z2 - x2 * z
    return a / 2


def centroid(poly):
    a = poly_area(poly)
    if abs(a) < 1e-6:
        return (
            sum(p[0] for p in poly) / len(poly),
            sum(p[1] for p in poly) / len(poly),
        )
    cx = cz = 0.0
    for i in range(len(poly)):
        x, z = poly[i]
        x2, z2 = poly[(i + 1) % len(poly)]
        c = x * z2 - x2 * z
        cx += (x + x2) * c
        cz += (z + z2) * c
    return cx / (6 * a), cz / (6 * a)


def point_in(poly, x, z):
    inside = False
    j = len(poly) - 1
    for i in range(len(poly)):
        xi, zi = poly[i]
        xj, zj = poly[j]
        if ((zi > z) != (zj > z)) and (x < (xj - xi) * (z - zi) / ((zj - zi) or 1e-9) + xi):
            inside = not inside
        j = i
    return inside


def clean_poly(poly):
    out = []
    for p in poly:
        if not out or hypot(p[0] - out[-1][0], p[1] - out[-1][1]) > 0.15:
            out.append((float(p[0]), float(p[1])))
    if len(out) > 2 and hypot(out[0][0] - out[-1][0], out[0][1] - out[-1][1]) < 0.15:
        out.pop()
    return out


def hash01(n, salt):
    x = math.sin(n * 127.1 + salt * 311.7) * 43758.5453
    return x - math.floor(x)


def yaw_quat(yaw):
    h = yaw * 0.5
    return (0.0, math.sin(h), 0.0, math.cos(h))


def face_yaw(nx, nz):
    """Yaw that aims a +Z-facing prototype along the outward normal (nx, nz)."""
    return math.atan2(nx, nz)


class Prim:
    def __init__(self):
        self.P, self.N, self.U, self.C, self.I = [], [], [], [], []

    def v(self, p, n, uv, c):
        self.P.append(p)
        self.N.append(n)
        self.U.append(uv)
        self.C.append(c)
        return len(self.P) - 1

    def tri(self, a, b, c, color, uvs=None):
        n = self._n(a, b, c)
        if n is None:
            return
        uv = uvs or ((0, 0), (1, 0), (1, 1))
        i0 = self.v(a, n, uv[0], color)
        i1 = self.v(b, n, uv[1], color)
        i2 = self.v(c, n, uv[2], color)
        self.I.extend((i0, i1, i2))

    def quad(self, a, b, c, d, color, uvs=None):
        # A quad is only stored when both triangles have area. A zero-length
        # normal becomes NaN in MeshStandardMaterial and has taken down the
        # whole street view on some GPUs.
        n = self._n(a, b, c) or self._n(a, c, d)
        if n is None:
            return
        uv = uvs or ((0, 0), (1, 0), (1, 1), (0, 1))
        ids = [self.v(p, n, u, color) for p, u in zip((a, b, c, d), uv)]
        self.I.extend((ids[0], ids[1], ids[2], ids[0], ids[2], ids[3]))

    @staticmethod
    def _n(a, b, c):
        ux, uy, uz = b[0] - a[0], b[1] - a[1], b[2] - a[2]
        vx, vy, vz = c[0] - a[0], c[1] - a[1], c[2] - a[2]
        nx = uy * vz - uz * vy
        ny = uz * vx - ux * vz
        nz = ux * vy - uy * vx
        L = math.sqrt(nx * nx + ny * ny + nz * nz)
        if L < 1e-6:
            return None
        return (nx / L, ny / L, nz / L)

    @property
    def tris(self):
        return len(self.I) // 3


def box(prim, cx, cy, cz, sx, sy, sz, color):
    hx, hy, hz = sx / 2, sy / 2, sz / 2
    x0, x1 = cx - hx, cx + hx
    y0, y1 = cy - hy, cy + hy
    z0, z1 = cz - hz, cz + hz
    faces = [
        ((x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1)),
        ((x1, y0, z0), (x0, y0, z0), (x0, y1, z0), (x1, y1, z0)),
        ((x0, y1, z1), (x1, y1, z1), (x1, y1, z0), (x0, y1, z0)),
        ((x0, y0, z0), (x1, y0, z0), (x1, y0, z1), (x0, y0, z1)),
        ((x1, y0, z1), (x1, y0, z0), (x1, y1, z0), (x1, y1, z1)),
        ((x0, y0, z0), (x0, y0, z1), (x0, y1, z1), (x0, y1, z0)),
    ]
    for f in faces:
        prim.quad(*f, color)


def cyl(prim, cx, cy, cz, r, h, color, seg=8, axis="y"):
    y0, y1 = cy, cy + h
    ring0, ring1 = [], []
    for i in range(seg):
        a = (i / seg) * math.tau
        if axis == "y":
            ring0.append((cx + math.cos(a) * r, y0, cz + math.sin(a) * r))
            ring1.append((cx + math.cos(a) * r, y1, cz + math.sin(a) * r))
        else:
            ring0.append((cx, cy + math.cos(a) * r, cz + math.sin(a) * r))
            ring1.append((cx + h, cy + math.cos(a) * r, cz + math.sin(a) * r))
    for i in range(seg):
        j = (i + 1) % seg
        prim.quad(ring0[i], ring0[j], ring1[j], ring1[i], color)
    c0 = (cx, y0, cz) if axis == "y" else (cx, cy, cz)
    c1 = (cx, y1, cz) if axis == "y" else (cx + h, cy, cz)
    for i in range(seg):
        j = (i + 1) % seg
        prim.tri(c0, ring0[j], ring0[i], color)
        prim.tri(c1, ring1[i], ring1[j], color)


class Atlas:
    def __init__(self, size=2048):
        self.size = size
        self.im = Image.new("RGB", (size, size), (40, 32, 28))
        self.draw = ImageDraw.Draw(self.im)
        self.font = ImageFont.truetype(FONT, 42)
        self.font_sm = ImageFont.truetype(FONT, 28)
        self.font_lg = ImageFont.truetype(FONT, 64)
        self.cells = {}
        self._next = 0
        # Reserve the top band for special boards.
        self.special_y = 0

    def _uv(self, x, y, w, h):
        S = self.size
        # glTF v=0 is the top of the image. Bottom of the board gets the
        # bottom of the cell; top of the board gets the top.
        return (x / S, (y + h) / S, (x + w) / S, y / S)

    def add_shop(self, text):
        S = self.size
        w, h = 256, 64
        cols = S // w
        # start below the 320px special band
        i = self._next
        self._next += 1
        col = i % cols
        row = i // cols
        x, y = col * w, 320 + row * h
        if y + h > S:
            x, y = 0, 320
        self.draw.rectangle((x, y, x + w - 1, y + h - 1), fill=(245, 240, 226))
        self.draw.rectangle((x, y, x + w - 1, y + h - 1), outline=(40, 28, 20), width=4)
        label = text.upper()[:22]
        size = 40 if len(label) < 12 else 28
        font = ImageFont.truetype(FONT, size)
        tw, th = size, size
        for _ in range(6):
            bbox = self.draw.textbbox((0, 0), label, font=font)
            tw, th = bbox[2] - bbox[0], bbox[3] - bbox[1]
            if tw <= w - 20 and th <= h - 12:
                break
            size = max(13, int(size * min((w - 20) / max(tw, 1), (h - 12) / max(th, 1))))
            font = ImageFont.truetype(FONT, size)
        self.draw.text(
            (x + (w - tw) / 2, y + (h - th) / 2 - 2),
            label,
            fill=(28, 18, 12),
            font=font,
        )
        u = self._uv(x, y, w, h)
        self.cells[text] = u
        return u

    def street_blade(self):
        x, y, w, h = 0, 0, 1024, 280
        self.draw.rounded_rectangle((x + 8, y + 8, x + w - 8, y + h - 8), radius=36, fill=(24, 102, 184))
