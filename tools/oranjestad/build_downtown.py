def flatten(lines):
    # chain loosely by concatenation; distance tests don't need a single chain
    out = []
    for ln in lines:
        if out and hypot(out[-1][0] - ln[0][0], out[-1][1] - ln[0][1]) < 3:
            out.extend(ln[1:])
        else:
            if out:
                out.append(out[-1])  # break marker avoided; keep separate via big jump
            out.extend(ln)
    return out


