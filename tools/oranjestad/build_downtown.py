class Glb:
    def __init__(self, name):
        self.name = name
        self.prims = []  # (prim, material)
        self.mats = {}
        self.images = []  # (bytes, mime)
        self.instances = []  # (prim, material, list of (pos, quat, scale))
        self.lod0_nodes = []
        self.lod1_prim = None

    def mat(self, name, **kwargs):
        self.mats[name] = kwargs
        return name

    def add(self, prim, material):
        if prim.tris == 0:
            return
        self.prims.append((prim, material))
        self.lod0_nodes.append(("mesh", len(self.prims) - 1))

    def add_instances(self, prim, material, xforms):
        if not xforms or prim.tris == 0:
            return
        self.instances.append((prim, material, xforms))

    def pack(self):
        # binary
        blob = bytearray()
        views = []
        accessors = []

        def align(n=4):
            while len(blob) % n:
                blob.append(0)

        def push(data, target=None):
            align(4)
            off = len(blob)
            blob.extend(data)
            views.append({"buffer": 0, "byteOffset": off, "byteLength": len(data), **({"target": target} if target else {})})
            return len(views) - 1

        def acc(view, count, ctype, typ, mins=None, maxs=None):
            a = {"bufferView": view, "componentType": ctype, "count": count, "type": typ}
            if mins is not None:
                a["min"] = mins
                a["max"] = maxs
            accessors.append(a)
            return len(accessors) - 1

        F32, U16, U32 = 5126, 5123, 5125

        def f32(values):
            return struct.pack("<" + "f" * len(values), *values)

        meshes = []
        mesh_ids = []

        def emit_prim(prim, material):
            idx = prim.I
            use32 = len(prim.P) > 65535
            idata = b"".join(struct.pack("<I" if use32 else "<H", i) for i in idx)
            # pad
            iv = push(idata, 34963)
            ia = acc(iv, len(idx), U32 if use32 else U16, "SCALAR")
            flatP, flatN, flatU, flatC = [], [], [], []
            for p, n, u, c in zip(prim.P, prim.N, prim.U, prim.C):
                flatP.extend(p)
                flatN.extend(n)
                flatU.extend(u)
                flatC.extend(c)
            pv = push(f32(flatP), 34962)
            nv = push(f32(flatN), 34962)
            uv = push(f32(flatU), 34962)
            cv = push(f32(flatC), 34962)

            def bounds(vals, n):
                cols = [vals[i::n] for i in range(n)]
                return [min(c) for c in cols], [max(c) for c in cols]

            pmin, pmax = bounds(flatP, 3)
            pa = acc(pv, len(prim.P), F32, "VEC3", pmin, pmax)
            na = acc(nv, len(prim.N), F32, "VEC3")
            ua = acc(uv, len(prim.U), F32, "VEC2")
            ca = acc(cv, len(prim.C), F32, "VEC3")
            meshes.append(
                {
                    "primitives": [
                        {
                            "attributes": {"POSITION": pa, "NORMAL": na, "TEXCOORD_0": ua, "COLOR_0": ca},
                            "indices": ia,
                            "material": material,
                        }
                    ]
                }
            )
            return len(meshes) - 1

        mat_index = {}
        # materials filled after we know textures; placeholder order
        # We'll assign indices in the order mats were created, image 0 if textured.

        # First emit geometry so accessors exist, materials referenced by name then remapped.
        named_prims = []
        for prim, mat_name in self.prims:
            named_prims.append((prim, mat_name, None))
        inst_entries = []
        for prim, mat_name, xforms in self.instances:
            named_prims.append((prim, mat_name, xforms))

        # Build meshes
        node_defs = []  # dicts
        for prim, mat_name, xforms in named_prims:
            mid = emit_prim(prim, mat_name)
            node = {"mesh": mid}
            if xforms is not None:
                trans, rots, scales = [], [], []
                for pos, quat, scale in xforms:
                    trans.extend(pos)
                    rots.extend(quat)
                    scales.extend(scale)
                n = len(xforms)
                tv = push(f32(trans))
                rv = push(f32(rots))
                sv = push(f32(scales))

                def b3(vals):
                    xs, ys, zs = vals[0::3], vals[1::3], vals[2::3]
                    return [min(xs), min(ys), min(zs)], [max(xs), max(ys), max(zs)]

                tmin, tmax = b3(trans)
                ta = acc(tv, n, F32, "VEC3", tmin, tmax)
                ra = acc(rv, n, F32, "VEC4")
                sa = acc(sv, n, F32, "VEC3")
                node["extensions"] = {
                    "EXT_mesh_gpu_instancing": {
                        "attributes": {"TRANSLATION": ta, "ROTATION": ra, "SCALE": sa}
                    }
                }
            node_defs.append(node)

        # lod1
        lod1_index = None
        if self.lod1_prim and self.lod1_prim.tris:
            lod1_index = emit_prim(self.lod1_prim, "paint")

        # images
        image_defs = []
        for png, mime in self.images:
            iv = push(png)
            image_defs.append({"bufferView": iv, "mimeType": mime})

        mat_names = list(dict.fromkeys([m for _, m, _ in named_prims] + (["paint"] if lod1_index is not None else [])))
        materials = []
        for name in mat_names:
            spec = self.mats.get(name, {})
            m = {
                "name": name,
                "pbrMetallicRoughness": {
                    "baseColorFactor": spec.get("color", [1, 1, 1, 1]),
                    "metallicFactor": spec.get("metal", 0.0),
                    "roughnessFactor": spec.get("rough", 0.84),
                },
                "doubleSided": spec.get("double", False),
            }
            if spec.get("tex") is not None and image_defs:
                m["pbrMetallicRoughness"]["baseColorTexture"] = {"index": spec["tex"]}
            materials.append(m)
        mat_of = {n: i for i, n in enumerate(mat_names)}

        # remap material names stored in primitives
        for mesh in meshes:
            for prim in mesh["primitives"]:
                prim["material"] = mat_of[prim["material"]]

        # nodes: lod groups
        nodes = []
        # child nodes first
        child_ids = []
        for nd in node_defs:
            child_ids.append(len(nodes))
            nodes.append(nd)
        lod0 = {"name": f"{self.name}_lod0", "children": child_ids}
        lod0_id = len(nodes)
        nodes.append(lod0)
        scene_nodes = [lod0_id]
        if lod1_index is not None:
            nodes.append({"name": f"{self.name}_lod1", "mesh": lod1_index})
            scene_nodes.append(len(nodes) - 1)

        gltf = {
            "asset": {"version": "2.0", "generator": "aruba-oranjestad"},
            "extensionsUsed": ["EXT_mesh_gpu_instancing"] if self.instances else [],
            "scene": 0,
            "scenes": [{"nodes": scene_nodes}],
            "nodes": nodes,
            "meshes": meshes,
            "materials": materials,
            "accessors": accessors,
            "bufferViews": views,
            "buffers": [{"byteLength": len(blob)}],
        }
        if image_defs:
            gltf["images"] = image_defs
            gltf["textures"] = [{"source": i, "sampler": 0} for i in range(len(image_defs))]
            # LINEAR, not a mipmap filter: an incomplete mip chain samples black on the phone path.
            gltf["samplers"] = [{"magFilter": 9729, "minFilter": 9729, "wrapS": 33071, "wrapT": 33071}]
