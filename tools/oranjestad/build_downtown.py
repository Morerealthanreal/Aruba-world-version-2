def gable_pts(kind):
    """Profile in (along-facade 0..1, metres above the eave).

    The three kinds are deliberately different silhouettes: a tall stepped
    gable, a neck gable, and a scrolled pediment. Peaks sit well above the
    street canopies so the row reads from the sidewalk, not only head-on.
    """
    if kind == 0:  # stepped
        return [
            (0.00, 0.45), (0.10, 0.45),
            (0.10, 1.55), (0.24, 1.55),
            (0.24, 2.65), (0.36, 2.65),
            (0.36, 3.85), (0.64, 3.85),
            (0.64, 2.65), (0.76, 2.65),
            (0.76, 1.55), (0.90, 1.55),
            (0.90, 0.45), (1.00, 0.45),
        ]
    if kind == 1:  # neck / bell
        return [
            (0.00, 0.40), (0.07, 1.15), (0.15, 2.15), (0.24, 2.95),
            (0.34, 3.45), (0.43, 4.15), (0.50, 4.70), (0.57, 4.15),
            (0.66, 3.45), (0.76, 2.95), (0.85, 2.15), (0.93, 1.15),
            (1.00, 0.40),
        ]
    # scrolled pediment
    return [
        (0.00, 0.50), (0.08, 0.85), (0.18, 1.70), (0.30, 2.70),
        (0.42, 3.35), (0.50, 3.60), (0.58, 3.35), (0.70, 2.70),
        (0.82, 1.70), (0.92, 0.85), (1.00, 0.50),
    ]


def extrude_walls(prim, poly, y0, y1, color, origin, h0):
    """Walls of an arbitrary footprint. y0/y1 are world heights."""
    area = poly_area(poly)
    ccw = area > 0
    ox, oz = origin
    for i in range(len(poly)):
        a, b = poly[i], poly[(i + 1) % len(poly)]
        dx, dz = b[0] - a[0], b[1] - a[1]
        L = hypot(dx, dz)
        if L < 0.4:
            continue
        # quad facing outward. Our quad winding faces the LEFT of a->b.
        # Outward for CCW (interior left) is the RIGHT, so swap the edge.
        p0 = (a[0] - ox, y0 - h0, a[1] - oz)
        p1 = (b[0] - ox, y0 - h0, b[1] - oz)
        p2 = (b[0] - ox, y1 - h0, b[1] - oz)
        p3 = (a[0] - ox, y1 - h0, a[1] - oz)
        if ccw:
            prim.quad(p1, p0, p3, p2, color)
        else:
            prim.quad(p0, p1, p2, p3, color)


def street_edge(poly, road):
    area = poly_area(poly)
    ccw = area > 0
    best = None
    for i in range(len(poly)):
        a, b = poly[i], poly[(i + 1) % len(poly)]
        mx, mz = (a[0] + b[0]) / 2, (a[1] + b[1]) / 2
        d, _, _ = dist_point_seg((mx, mz), *nearest_seg((mx, mz), road)) if False else (1e9, None, None)
        d = min_dist_to_poly((mx, mz), road)
        dx, dz = b[0] - a[0], b[1] - a[1]
        L = hypot(dx, dz) or 1
        # left normal
        ln = (-dz / L, dx / L)
        outward = ln if not ccw else (dz / L, -dx / L)
        # prefer edges whose outward normal points toward the road
        # vector from midpoint to closest road point
        q = closest_on_line((mx, mz), road)
        toward = norm((q[0] - mx, q[1] - mz))
        facing = dot(outward, toward)
        score = facing * 2.2 - d * 0.04 + min(L, 18) * 0.01
        if best is None or score > best[0]:
            best = (score, i, a, b, L, outward, d)
    return best


def min_dist_to_poly(p, line):
    best = 1e9
    for i in range(len(line) - 1):
        d, _, _ = dist_point_seg(p, line[i], line[i + 1])
        best = min(best, d)
    return best


def closest_on_line(p, line):
    best = 1e9
    q = line[0]
    for i in range(len(line) - 1):
        d, qq, _ = dist_point_seg(p, line[i], line[i + 1])
        if d < best:
            best, q = d, qq
    return q


def nearest_seg(p, line):
    best = 1e9
    seg = (line[0], line[1])
    for i in range(len(line) - 1):
        d, _, _ = dist_point_seg(p, line[i], line[i + 1])
        if d < best:
            best = d
            seg = (line[i], line[i + 1])
    return seg


def parapet(prim, a, b, outward, y_eave, color, trim, origin, h0, kind, scale=1.0):
    ox, oz = origin
    dx, dz = b[0] - a[0], b[1] - a[1]
    L = hypot(dx, dz) or 1
    tx, tz = dx / L, dz / L
    nx, nz = outward
    # Exact vertical risers (repeated t) used to emit zero-area quads.
    # Nudge them into a real step face so the silhouette keeps its area.
    pts = []
    for t, h in gable_pts(kind):
        h *= scale
        if pts and abs(t - pts[-1][0]) < 1e-3:
            t = min(0.985, pts[-1][0] + 0.032)
        pts.append((t, h))
    # pull the parapet just outside the wall; the back face sits ~1m into
    # the roof so the gable has a visible end when you look along the street
    inset = 0.10

    def world(t, y):
        return (
            a[0] + tx * L * t + nx * inset - ox,
            y - h0,
            a[1] + tz * L * t + nz * inset - oz,
        )

    # Quad order (t0 -> t1 -> up) has xz normal (-tz, tx). OSM footprints here
    # are clockwise, so that normal is the street side. Flip when it isn't.
    face_out = (-tz) * nx + tx * nz >= 0

    def ribbon(p00, p10, p11, p01, col):
        if face_out:
            prim.quad(p00, p10, p11, p01, col)
        else:
            prim.quad(p10, p00, p01, p11, col)

    for i in range(len(pts) - 1):
        t0, h0p = pts[i]
        t1, h1p = pts[i + 1]
        yb = y_eave
        top0, top1 = y_eave + h0p, y_eave + h1p
        ribbon(world(t0, yb), world(t1, yb), world(t1, top1), world(t0, top0), color)
        # white cap, plus a deep back ribbon so the gable reads down the street
        lift = 0.32
        out = 0.28

        def cap(t, h, push):
            return (
                a[0] + tx * L * t + nx * (inset + push) - ox,
                y_eave + h + lift * 0.3 - h0,
                a[1] + tz * L * t + nz * (inset + push) - oz,
            )

        ribbon(world(t0, top0), world(t1, top1), cap(t1, h1p, out), cap(t0, h0p, out), trim)
        back = -1.05

        def backp(t, y):
            return (
                a[0] + tx * L * t + nx * (inset + back) - ox,
                y - h0,
                a[1] + tz * L * t + nz * (inset + back) - oz,
            )

        # back face points into the roof
        if face_out:
            prim.quad(backp(t1, yb), backp(t0, yb), backp(t0, top0), backp(t1, top1), color)
        else:
            prim.quad(backp(t0, yb), backp(t1, yb), backp(t1, top1), backp(t0, top0), color)
        ribbon(cap(t0, h0p, out), cap(t1, h1p, out), backp(t1, top1), backp(t0, top0), trim)
    # white finial on the peak, so each gable has a bright marker from the sidewalk
    ti, hi = max(pts, key=lambda p: p[1])
    tip = world(ti, y_eave + hi)
    box(prim, tip[0], tip[1] + 0.55, tip[2], 0.36, 1.05, 0.36, trim)
    box(prim, tip[0], tip[1] + 1.15, tip[2], 0.62, 0.18, 0.62, trim)


