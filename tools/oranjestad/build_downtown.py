def build_skyline(road_smith):
    """Gable crowns along the street face of Royal Plaza and Renaissance Mall.

    The existing hero masses stay. These parapets supply the repeated Dutch
    gables that read from the harbour and from L.G. Smith.
    """
    manifest = json.loads(MANIFEST.read_text())
    paint = Prim()
    pieces = []
    specs = [
        # Stepped gables clear the pink roof so the street face matches the
        # harbour photo: tall white-trimmed peaks, not a flat parapet.
        ("royalplaza", (0.93, 0.52, 0.68), 0, 11.8, 1.45),
        ("renmall", (0.95, 0.78, 0.32), 2, 8.4, 0.72),
    ]
    ox = oz = None
    for hid, color, kind, eave_h, gscale in specs:
        hero = next(e for e in manifest if e["id"] == hid)
        fp = hero.get("hide_footprint")
        if not fp or len(fp) < 3:
            continue
        poly = clean_poly([(p[0], p[1]) for p in fp])
        if ox is None:
            ox, oz = hero["x"], hero["z"]
        edge = street_edge(poly, road_smith)
        if not edge:
            continue
        _, _, a, b, L, outward, _ = edge
        ground = height_at(*centroid(poly))
        eave = ground + eave_h
        n = max(3, min(8, int(L / 7.5)))
        dx, dz = (b[0] - a[0]) / L, (b[1] - a[1]) / L
        for k in range(n):
            aa = (a[0] + dx * L * k / n, a[1] + dz * L * k / n)
            bb = (a[0] + dx * L * (k + 1) / n, a[1] + dz * L * (k + 1) / n)
            parapet(paint, aa, bb, outward, eave, color, WHITE, (ox, oz), height_at(ox, oz), kind, scale=gscale)
        # teal awning band under the gables (Royal Plaza) / orange roof lip
        if hid == "royalplaza":
            nx, nz = outward
            y = eave - 1.15
            h0 = height_at(ox, oz)
            paint.quad(
                (a[0] + nx * 0.8 - ox, y - h0, a[1] + nz * 0.8 - oz),
                (b[0] + nx * 0.8 - ox, y - h0, b[1] + nz * 0.8 - oz),
                (b[0] + nx * 1.5 - ox, y - 0.35 - h0, b[1] + nz * 1.5 - oz),
                (a[0] + nx * 1.5 - ox, y - 0.35 - h0, a[1] + nz * 1.5 - oz),
                (0.35, 0.78, 0.82),
            )
        pieces.append(hid)
    if ox is None:
        return None, None
    h0 = height_at(ox, oz)
    lod = Prim()
    # lod is just a low hint so the group still switches
    box(lod, 0, 6, 0, 4, 2, 4, PASTELS[0])
    glb = Glb("ora_skyline")
    glb.mat("paint", rough=0.8)
    glb.add(paint, "paint")
    glb.lod1_prim = lod
    return glb, (ox, oz)


def clear_shop_signs(buildings):
    """Drop facade billboards on shops we replaced, so the gable sign is the name."""
    data = json.loads(LANDMARKS.read_text())
    cleared = 0
    for lm in data:
        x, z = lm.get("x"), lm.get("z")
        if x is None:
            continue
        foot = lm.get("foot")
        for b in buildings:
            hit = point_in(b["poly"], x, z)
            if not hit and foot and len(foot) > 2:
                fc = centroid([(p[0], p[1]) for p in foot])
                hit = point_in(b["poly"], fc[0], fc[1])
            if hit:
                if lm.get("foot"):
                    lm["foot"] = None
                    cleared += 1
                # keep the name for search; the hero sign carries the board
                break
    if cleared:
        LANDMARKS.write_text(json.dumps(data, separators=(",", ":")))
    return cleared


def upsert_manifest(entries, replace_ids):
    manifest = json.loads(MANIFEST.read_text())
    by_id = {e["id"]: e for e in manifest}
    for ent in entries:
        if ent["id"] in by_id:
            old = by_id[ent["id"]]
            old["glb"] = ent["glb"]
            old["lod"] = ent["lod"]
            old["tris"] = ent["tris"]
            old["textures"] = ent["textures"]
            old["ref_sources"] = ent["ref_sources"]
            old["status"] = ent["status"]
        else:
            manifest.append(ent)
    # drop nothing else
    MANIFEST.write_text(json.dumps(manifest, indent=1))


