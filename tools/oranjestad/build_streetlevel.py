def audit(path):
    data = path.read_bytes()
    n = struct.unpack_from("<I", data, 12)[0]
    gltf = json.loads(data[20 : 20 + n])
    blob = data[20 + n + 8 :]
    views = gltf["bufferViews"]
    accs = gltf["accessors"]
    bad = 0
    for mesh in gltf["meshes"]:
        for prim in mesh["primitives"]:
            pa = accs[prim["attributes"]["POSITION"]]
            ia = accs[prim["indices"]]
            pv = views[pa["bufferView"]]
            iv = views[ia["bufferView"]]
            stride = pv.get("byteStride", 12)
            pos = []
            for i in range(pa["count"]):
                o = pv["byteOffset"] + i * stride
                pos.append(struct.unpack_from("<fff", blob, o))
            idx = []
            io = iv["byteOffset"]
            for i in range(ia["count"]):
                idx.append(struct.unpack_from("<H", blob, io + i * 2)[0])
            for t in range(0, len(idx), 3):
                a, b, c = (pos[idx[t + k]] for k in range(3))
                ux, uy, uz = b[0] - a[0], b[1] - a[1], b[2] - a[2]
                vx, vy, vz = c[0] - a[0], c[1] - a[1], c[2] - a[2]
                nx = uy * vz - uz * vy
                ny = uz * vx - ux * vz
                nz = ux * vy - uy * vx
                if nx * nx + ny * ny + nz * nz < 1e-12:
                    bad += 1
    print(f"  audit {path.name}: zero-area tris {bad}")
    return bad


