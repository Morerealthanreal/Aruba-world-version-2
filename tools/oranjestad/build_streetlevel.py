def chain_roads(pred, box):
    """Join named road segments whose samples fall inside box=(x0,x1,z0,z1)."""
    x0, x1, z0, z1 = box
    segs = []
    for fn in ("r_3_11.json", "r_3_12.json", "r_4_11.json", "r_4_12.json"):
        data = json.loads((REAL / fn).read_text())
        for road in data["roads"]:
            if not pred(road.get("n") or ""):
                continue
            pts = [(p[0], p[1]) for p in road["p"] if x0 <= p[0] <= x1 and z0 <= p[1] <= z1]
            if len(pts) >= 2:
                segs.append(pts)
    # Greedy join on shared endpoints.
    used = [False] * len(segs)
    lines = []
    for i, seg in enumerate(segs):
        if used[i]:
            continue
        used[i] = True
        line = list(seg)
        grew = True
        while grew:
            grew = False
            for j, other in enumerate(segs):
                if used[j]:
                    continue
                if hypot2(line[-1], other[0]) < 4:
                    line.extend(other[1:])
                elif hypot2(line[-1], other[-1]) < 4:
                    line.extend(reversed(other[:-1]))
                elif hypot2(line[0], other[-1]) < 4:
                    line = other[:-1] + line
                elif hypot2(line[0], other[0]) < 4:
                    line = list(reversed(other[1:])) + line
                else:
                    continue
                used[j] = True
                grew = True
        if len(line) >= 2:
            lines.append(line)
    lines.sort(key=lambda ln: -sum(math.hypot(b[0] - a[0], b[1] - a[1]) for a, b in zip(ln, ln[1:])))
    return lines[0] if lines else []


def hypot2(a, b):
    return (a[0] - b[0]) ** 2 + (a[1] - b[1]) ** 2


def samples(line, step):
    """(x, z, tx, tz, lx, lz) along the centreline. Left normal is unit."""
    out = []
    if len(line) < 2:
        return out
    acc = 0.0
    nxt = 0.0
    for a, b in zip(line, line[1:]):
        dx, dz = b[0] - a[0], b[1] - a[1]
        L = math.hypot(dx, dz)
        if L < 0.4:
            continue
        tx, tz = dx / L, dz / L
        lx, lz = -tz, tx
        while acc + (L if nxt == 0 else 0) >= nxt or True:
            if nxt > acc + L:
                break
            t = (nxt - acc) / L
            out.append((a[0] + dx * t, a[1] + dz * t, tx, tz, lx, lz))
            nxt += step
        acc += L
    return out


def land(x, z, buildings, min_h=1.25):
    h = height_at(x, z)
    if h < min_h:
        return None
    for b in buildings:
        if point_in(b["poly"], x, z):
            return None
    return h


def near_any(x, z, pts, r):
    r2 = r * r
    for p in pts:
        if (p[0] - x) ** 2 + (p[1] - z) ** 2 < r2:
            return True
    return False


def load_cars():
    cars = []
    for fn in ("st_3_11.json", "st_3_12.json", "st_4_11.json", "st_4_12.json"):
        data = json.loads((REAL / fn).read_text())
        for c in data.get("cars") or []:
            if isinstance(c, list) and len(c) >= 2:
                cars.append((c[0], c[1]))
    return cars


def local(x, y, z, origin):
    ox, oz, h0 = origin
    return (x - ox, y - h0, z - oz)


def xform(x, y, z, origin, yaw=0.0, scale=1.0):
    return (local(x, y, z, origin), yaw_quat(yaw), (scale, scale, scale))


def upward(a, b, c, d):
    ux, uy, uz = b[0] - a[0], b[1] - a[1], b[2] - a[2]
    vx, vy, vz = d[0] - a[0], d[1] - a[1], d[2] - a[2]
    ny = uz * vx - ux * vz
    if ny < 0:
        return a, d, c, b
    return a, b, c, d


def ground_cell(prim, corners, color, origin):
    ox, oz, h0 = origin
    pts = []
    hs = []
    for x, z in corners:
        h = height_at(x, z)
        if h < 1.2:
            return
        hs.append(h)
        pts.append((x - ox, h + LIFT - h0, z - oz))
    if max(hs) - min(hs) > 1.6:
        return
    prim.quad(*upward(*pts), color)


def curb(prim, a, b, origin):
    """Low concrete curb between two world points, facing the street."""
    ox, oz, h0 = origin
    ha, hb = height_at(*a), height_at(*b)
    if ha < 1.2 or hb < 1.2 or abs(ha - hb) > 1.6:
        return
    def p(x, z, y):
        return (x - ox, y - h0, z - oz)
    top = 0.16
    a0 = p(*a, ha + LIFT)
    b0 = p(*b, hb + LIFT)
    a1 = p(*a, ha + LIFT + top)
    b1 = p(*b, hb + LIFT + top)
    # Vertical face. Winding is corrected by the quad skip if degenerate.
    prim.quad(a0, b0, b1, a1, CONCRETE)
    prim.quad(a1, b1, b0, a0, CONCRETE)
    # Cap, a few centimetres toward the sidewalk so the top has width.
    dx, dz = b[0] - a[0], b[1] - a[1]
    L = math.hypot(dx, dz) or 1
    nx, nz = -dz / L, dx / L
    cap = 0.18
    c0 = p(a[0] + nx * cap, a[1] + nz * cap, ha + LIFT + top)
    c1 = p(b[0] + nx * cap, b[1] + nz * cap, hb + LIFT + top)
    prim.quad(*upward(a1, b1, c1, c0), CONCRETE)


