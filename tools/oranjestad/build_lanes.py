def short_name(name):
    text = (name or "").strip()
    for suffix in (
        " Department Store",
        " Supermarket",
        " Supermercado",
        " Restaurant",
        " Mini Market",
        " Gift Shop",
        " Souveneirs",
        " Souvenirs",
        " Bar & Restaurant",
        " Bar and Restaurant",
        " N.V.",
    ):
        if text.lower().endswith(suffix.lower()):
            text = text[: -len(suffix)]
    text = text.strip(" -")
    return text[:18]


def sign_uv(atlas, text, bg, fg):
    w, h = 256, 64
    cols = atlas.size // w
    i = atlas._next
    atlas._next += 1
    x, y = (i % cols) * w, 8 + (i // cols) * h
    if y + h > atlas.size:
        x, y = 0, 8
    atlas.draw.rectangle((x, y, x + w - 1, y + h - 1), fill=bg)
    atlas.draw.rectangle((x + 4, y + 4, x + w - 5, y + h - 5), outline=fg, width=3)
    label = text.upper()[:18]
    size = 34 if len(label) < 12 else 24
    font = ImageFont.truetype(FONT, size)
    for _ in range(6):
        bbox = atlas.draw.textbbox((0, 0), label, font=font)
        tw, th = bbox[2] - bbox[0], bbox[3] - bbox[1]
        if tw <= w - 18 and th <= h - 10:
            break
        size = max(12, int(size * min((w - 18) / max(tw, 1), (h - 10) / max(th, 1))))
        font = ImageFont.truetype(FONT, size)
    atlas.draw.text((x + (w - tw) / 2, y + (h - th) / 2 - 2), label, fill=fg, font=font)
    return atlas._uv(x, y, w, h)


def quad_out(prim, p0, p1, p2, p3, color, prefer):
    n = Prim._n(p0, p1, p2)
    if n is None:
        return None
    if n[0] * prefer[0] + n[1] * prefer[1] + n[2] * prefer[2] >= 0:
        prim.quad(p0, p1, p2, p3, color)
        return True
    prim.quad(p1, p0, p3, p2, color)
    return False


def point_on(a, b, outward, t, y, proud, origin, h0):
    dx, dz = b[0] - a[0], b[1] - a[1]
    L = hypot(dx, dz) or 1.0
    tx, tz = dx / L, dz / L
    ox, oz = origin
    return (
        a[0] + tx * t + outward[0] * proud - ox,
        y - h0,
        a[1] + tz * t + outward[1] * proud - oz,
    )


def span(prim, a, b, outward, t0, t1, y0, y1, color, origin, h0, proud):
    if t1 - t0 < 0.22 or y1 - y0 < 0.12:
        return
    prefer = (outward[0], 0.15, outward[1])
    quad_out(
        prim,
        point_on(a, b, outward, t0, y0, proud, origin, h0),
        point_on(a, b, outward, t1, y0, proud, origin, h0),
        point_on(a, b, outward, t1, y1, proud, origin, h0),
        point_on(a, b, outward, t0, y1, proud, origin, h0),
        color,
        prefer,
    )


def sign_span(signs, uv, a, b, outward, t0, t1, y0, y1, origin, h0, proud):
    u0, v0, u1, v1 = uv
    p0 = point_on(a, b, outward, t0, y0, proud, origin, h0)
    p1 = point_on(a, b, outward, t1, y0, proud, origin, h0)
    p2 = point_on(a, b, outward, t1, y1, proud, origin, h0)
    p3 = point_on(a, b, outward, t0, y1, proud, origin, h0)
    n = Prim._n(p0, p1, p2)
    if n is None:
        return
    prefer = (outward[0], 0.1, outward[1])
    if n[0] * prefer[0] + n[2] * prefer[2] >= 0:
        signs.quad(p0, p1, p2, p3, (1, 1, 1), ((u0, v0), (u1, v0), (u1, v1), (u0, v1)))
    else:
        signs.quad(p1, p0, p3, p2, (1, 1, 1), ((u1, v0), (u0, v0), (u0, v1), (u1, v1)))


def awning(prim, a, b, outward, t0, t1, y, color, origin, h0):
    """A canvas shade that projects toward the sidewalk and drops at the lip."""
    p0 = point_on(a, b, outward, t0, y, 0.16, origin, h0)
    p1 = point_on(a, b, outward, t1, y, 0.16, origin, h0)
    p2 = point_on(a, b, outward, t1, y - 0.42, 1.25, origin, h0)
    p3 = point_on(a, b, outward, t0, y - 0.42, 1.25, origin, h0)
    quad_out(prim, p0, p1, p2, p3, color, (outward[0], 0.4, outward[1]))


def hip(prim, poly, origin, h0, y_eave, rise, color):
    c = centroid(poly)
    peak = (c[0] - origin[0], y_eave + rise - h0, c[1] - origin[1])
    for i in range(len(poly)):
        p, q = poly[i], poly[(i + 1) % len(poly)]
        e0 = (p[0] - origin[0], y_eave - h0, p[1] - origin[1])
        e1 = (q[0] - origin[0], y_eave - h0, q[1] - origin[1])
        n = Prim._n(peak, e0, e1)
        if n is None:
            continue
        if n[1] >= 0:
            prim.tri(peak, e0, e1, color)
        else:
            prim.tri(peak, e1, e0, color)


def shop_bays(paint, glass, signs, atlas, a, b, outward, ground, origin, h0, names, seed, gable=True, claimed=None):
    dx, dz = b[0] - a[0], b[1] - a[1]
    L = hypot(dx, dz) or 1.0
    n = max(1, min(7, int(round(L / 5.6))))
    while n > 1 and L / n < 3.6:
        n -= 1
    eave = ground + 5.35
    used = []
    claimed = claimed if claimed is not None else set()
    for k in range(n):
        t0 = L * k / n
        t1 = L * (k + 1) / n
        wall = WALLS[(seed + k) % len(WALLS)]
        shade = AWNINGS[(seed + k * 2) % len(AWNINGS)]
        span(paint, a, b, outward, t0 + 0.06, t1 - 0.06, ground - 0.25, eave, wall, origin, h0, 0.14)
        # White pier between shops.
        if k:
            span(paint, a, b, outward, t0 - 0.07, t0 + 0.07, ground - 0.2, eave + 0.08, TRIM, origin, h0, 0.2)
        door_w = 0.82
        span(paint, a, b, outward, t0 + 0.28, t0 + 0.28 + door_w, ground, ground + 2.15, DOOR, origin, h0, 0.22)
        win0 = t0 + 0.28 + door_w + 0.28
        win1 = t1 - 0.28
        if win1 - win0 > 0.7:
            span(glass, a, b, outward, win0, win1, ground + 0.55, ground + 2.15, GLASS, origin, h0, 0.2)
        awning(paint, a, b, outward, t0 + 0.18, t1 - 0.18, ground + 2.45, shade, origin, h0)
        # Two shuttered windows upstairs.
        span_w = (t1 - t0) / 2
        for s in (0.35, 1.15):
            cx = t0 + span_w * s
            span(paint, a, b, outward, cx - 0.38, cx + 0.38, ground + 3.35, ground + 4.45, TRIM, origin, h0, 0.2)
            span(glass, a, b, outward, cx - 0.26, cx + 0.26, ground + 3.48, ground + 4.32, GLASS, origin, h0, 0.26)
            span(paint, a, b, outward, cx - 0.62, cx - 0.38, ground + 3.4, ground + 4.4, SHUTTER, origin, h0, 0.24)
            span(paint, a, b, outward, cx + 0.38, cx + 0.62, ground + 3.4, ground + 4.4, SHUTTER, origin, h0, 0.24)
        span(paint, a, b, outward, t0 + 0.05, t1 - 0.05, eave - 0.16, eave + 0.08, TRIM, origin, h0, 0.22)
        label = claim_name(names, used, claimed, a, b, (t0 + t1) / 2)
        if label and t1 - t0 > 2.8:
            bg, fg = ((236, 228, 208), (28, 18, 12)) if k % 2 == 0 else ((18, 42, 78), (245, 242, 230))
            uv = sign_uv(atlas, label, bg, fg)
            sign_span(
                signs,
                uv,
                a,
                b,
                outward,
                t0 + 0.35,
                t1 - 0.35,
                ground + 2.62,
                ground + 3.22,
                origin,
                h0,
                0.28,
            )
        if gable and t1 - t0 > 4.0:
            aa = (
                a[0] + (b[0] - a[0]) * (t0 / L),
                a[1] + (b[1] - a[1]) * (t0 / L),
            )
            bb = (
                a[0] + (b[0] - a[0]) * (t1 / L),
                a[1] + (b[1] - a[1]) * (t1 / L),
            )
            parapet(paint, aa, bb, outward, eave, wall, TRIM, origin, h0, (seed + k) % 3, scale=0.62)
    return n


def claim_name(names, used, claimed, a, b, t):
    dx, dz = b[0] - a[0], b[1] - a[1]
    L = hypot(dx, dz) or 1.0
    x = a[0] + dx / L * t
    z = a[1] + dz / L * t
    best = None
    for i, (nx, nz, label) in enumerate(names):
        if i in used or not label or label in claimed:
            continue
        d = hypot(nx - x, nz - z)
        if d > 16:
            continue
        if best is None or d < best[0]:
            best = (d, i, label)
    if best is None:
        return ""
    used.append(best[1])
    claimed.add(best[2])
    return best[2]


def load_names():
    out = []
    data = json.loads(LANDMARKS.read_text())
    for lm in data:
        x, z = lm.get("x"), lm.get("z")
        name = short_name(lm.get("name") or "")
        if x is None or not name:
            continue
        if not (-7800 < x < -6600 and -220 < z < 260):
            continue
        low = name.lower()
        if any(word in low for word in SKIP_WORDS):
            continue
        out.append((x, z, name))
    return out


def street_lines():
    files = ("r_3_11.json", "r_3_12.json", "r_4_11.json", "r_4_12.json")
    lines = {}
    for name, (xb, zb) in STREETS.items():
        raw = load_named((name,), files)
        clipped = []
        for ln in raw:
            pts = [p for p in ln if xb[0] - 30 <= p[0] <= xb[1] + 30 and zb[0] - 30 <= p[1] <= zb[1] + 30]
            if len(pts) >= 2:
                clipped.append(pts)
        lines[name] = chain_lines(clipped, gap=22) if clipped else []
        print(f"  street {name}: {len(lines[name])} pts")
    return lines


def select(main_road, lines, names):
    buildings = load_buildings()
    blockers = hero_blockers()
    retire = set(STREET_IDS.values()) | {"ora_side", "ora_side0", "ora_side1", "ora_harbor"}
    blockers = (
        [p for p in blockers[0] if p[2] not in retire],
        [p for p in blockers[1] if p[1] not in retire],
    )
    picked = []
    for b in buildings:
        c = b["c"]
        if b["area"] < 28 or b["area"] > 480:
            continue
        if b.get("k") in ("hotel", "church", "ind"):
            continue
        if height_at(*c) < 1.1:
            continue
        if blocked(b, *blockers):
            continue
        if min_dist_to_poly(c, main_road) < 12:
            continue
        label = short_name(b.get("n") or "")
        low = label.lower()
        if any(word in low for word in SKIP_WORDS):
            continue
        best = None
        for street, (xb, zb) in STREETS.items():
            road = lines[street]
            if len(road) < 2:
                continue
            if not (xb[0] <= c[0] <= xb[1] and zb[0] <= c[1] <= zb[1]):
                continue
            dist = min_dist_to_poly(c, road)
            if dist > 16:
                continue
            if best is None or dist < best[0]:
                best = (dist, street, road)
        if best is None:
            continue
        _dist, street, road = best
        edge = street_edge(b["poly"], road)
        if edge is None or edge[4] < 4.0 or edge[6] > 14:
            continue
        row = dict(b)
        row["edge"] = edge
        row["street"] = street
        row["along"] = closest_on_line(c, road)[0]
        row["own_name"] = label
        picked.append(row)
    picked.sort(key=lambda b: (b["street"], b["along"]))
    print(f"side streets: {len(picked)}")
    for b in picked:
        print(f"    {b['street']}: {b['own_name'] or '(shop)'} ({b['c'][0]:.0f},{b['c'][1]:.0f})")
    return picked


def build_street(group, names):
    atlas = Atlas(size=1024)
    ox = sum(b["c"][0] for b in group) / len(group)
    oz = sum(b["c"][1] for b in group) / len(group)
    h0 = height_at(ox, oz)
    origin = (ox, oz)
    paint, glass, signs, lod = Prim(), Prim(), Prim(), Prim()
    bays = 0
    claimed = set()
    for i, b in enumerate(group):
        ground = height_at(*b["c"])
        eave = ground + 5.35
        extrude_walls(paint, b["poly"], ground - 0.35, eave, PLASTER, origin, h0)
        hip(paint, b["poly"], origin, h0, eave, 1.6, TERRACOTTA)
        _score, _i, a, bb, _L, outward, _d = b["edge"]
        local_names = list(names)
        if b["own_name"] and b["own_name"] not in claimed:
            local_names.append((b["c"][0], b["c"][1], b["own_name"]))
        bays += shop_bays(
            paint,
            glass,
            signs,
            atlas,
            a,
            bb,
            outward,
            ground,
            origin,
            h0,
            local_names,
            seed=int(hash01(b.get("i") or i, 5) * 8),
            claimed=claimed,
        )
        y1 = eave + 1.2
        ccw = poly_area(b["poly"]) > 0
        for k in range(len(b["poly"])):
            p, q = b["poly"][k], b["poly"][(k + 1) % len(b["poly"])]
            if hypot(p[0] - q[0], p[1] - q[1]) < 0.4:
                continue
            A = (p[0] - ox, ground - h0, p[1] - oz)
            B = (q[0] - ox, ground - h0, q[1] - oz)
            C = (q[0] - ox, y1 - h0, q[1] - oz)
            D = (p[0] - ox, y1 - h0, p[1] - oz)
            if ccw:
                lod.quad(B, A, D, C, WALLS[i % len(WALLS)])
            else:
                lod.quad(A, B, C, D, WALLS[i % len(WALLS)])
    return paint, glass, signs, atlas, lod, (ox, oz, h0), bays


def west_edges(poly):
    c = centroid(poly)
    out = []
    for i in range(len(poly)):
        a, b = poly[i], poly[(i + 1) % len(poly)]
        L = hypot(b[0] - a[0], b[1] - a[1])
        if L < 8:
            continue
        mx, mz = (a[0] + b[0]) / 2, (a[1] + b[1]) / 2
        ox, oz = mx - c[0], mz - c[1]
        n = hypot(ox, oz) or 1.0
        outward = (ox / n, oz / n)
        if outward[0] < -0.65:
            out.append((a, b, outward, L, mx, mz))
    return out


def build_harbor(names, dressed):
    """West faces seen from the harbour. Royal Plaza carries the pink gables;
    the low blocks in front of it carry the small shops."""
    manifest = json.loads(MANIFEST.read_text())
    royal = next(e for e in manifest if e["id"] == "royalplaza")
    poly = [(p[0], p[1]) for p in royal["hide_footprint"]]
    faces = west_edges(poly)
    if not faces:
        raise SystemExit("royal plaza has no west face")
    # The long water face.
    a, b, outward, L, mx, mz = max(faces, key=lambda f: f[3])
    ox, oz = mx, mz
    h0 = height_at(ox, oz)
    origin = (ox, oz)
    paint, glass, signs = Prim(), Prim(), Prim()
    atlas = Atlas(size=1024)
    ground = max(height_at(a[0], a[1]), height_at(b[0], b[1]), height_at(mx, mz))
    # Sit just outside the existing mall mesh.
    eave = ground + 9.4
    span(paint, a, b, outward, 0.4, L - 0.4, ground - 0.2, eave, PINK, origin, h0, 0.7)
    # White balcony band and teal awning, the two things the harbour photo shows.
    span(paint, a, b, outward, 0.5, L - 0.5, eave - 2.4, eave - 2.15, TRIM, origin, h0, 1.15)
    awning(paint, a, b, outward, 0.6, L - 0.6, ground + 3.3, TEAL, origin, h0)
    # A second, higher awning under the balcony.
    awning(paint, a, b, outward, 0.8, L - 0.8, eave - 2.5, TEAL, origin, h0)
    n = max(4, min(7, int(L / 6.5)))
    for k in range(n):
        t0, t1 = L * k / n, L * (k + 1) / n
        aa = (a[0] + (b[0] - a[0]) * (t0 / L), a[1] + (b[1] - a[1]) * (t0 / L))
        bb = (a[0] + (b[0] - a[0]) * (t1 / L), a[1] + (b[1] - a[1]) * (t1 / L))
        parapet(paint, aa, bb, outward, eave, PINK, TRIM, origin, h0, 0, scale=0.85)
        # Arched window pair under the gable.
        mid = (t0 + t1) / 2
        span(glass, a, b, outward, mid - 1.1, mid - 0.15, eave - 1.7, eave - 0.45, GLASS, origin, h0, 0.82)
        span(glass, a, b, outward, mid + 0.15, mid + 1.1, eave - 1.7, eave - 0.45, GLASS, origin, h0, 0.82)
    uv = sign_uv(atlas, "ROYAL PLAZA", (120, 28, 58), (255, 248, 240))
    sign_span(signs, uv, a, b, outward, L * 0.34, L * 0.66, ground + 3.55, ground + 4.35, origin, h0, 0.9)
    # Low shops on the water side of the boulevard, in front of the mall.
    buildings = load_buildings()
    near = []
    for b in buildings:
        c = b["c"]
        if not (-7820 < c[0] < -7640 and -110 < c[1] < 40):
            continue
        if b["area"] < 40 or b["area"] > 1600:
            continue
        if height_at(*c) < 1.0:
            continue
        key = (round(c[0], 1), round(c[1], 1))
        if key in dressed:
            continue
        faces_b = west_edges(b["poly"])
        if not faces_b:
            continue
        near.append((b, max(faces_b, key=lambda f: f[3])))
    print(f"harbor near-water shops {len(near)}")
    claimed = set()
    for i, (b, face) in enumerate(near):
        aa, bb, out, bl, _mx, _mz = face
        ground_b = height_at(*b["c"])
        shop_bays(
            paint,
            glass,
            signs,
            atlas,
            aa,
            bb,
            out,
            ground_b,
            origin,
            h0,
            names,
            seed=3 + i,
            gable=True,
            claimed=claimed,
        )
    lod = Prim()
    box(lod, 0, 4, 0, 10, 6, 4, PINK)
    return paint, glass, signs, atlas, lod, (ox, oz, h0), near


def pack(gid, paint, glass, signs, atlas, lod):
    glb = Glb(gid)
    glb.mat("paint", rough=0.84)
    glb.mat("glass", rough=0.22, metal=0.04)
    glb.images.append((atlas.png(), "image/png"))
    glb.add(paint, "paint")
    glb.add(glass, "glass")
    glb.mat("sign", rough=0.55, tex=0, double=True)
    glb.add(signs, "sign")
    glb.lod1_prim = lod
    glb.name = gid
    data, tris = glb.pack()
    path = HERO / f"{gid}.glb"
    path.write_bytes(data)
    if audit(path):
        raise SystemExit(f"{gid} degenerate")
    print(f"wrote {path.name} tris {tris}")
    return tris


