export function holdMissingHeroes(real: { hero?: { list?: { glb?: string; _loading?: boolean }[] } } | null) {
  const list = real?.hero?.list;
  if (!list) return 0;
  let n = 0;
  for (const e of list) {
    const g = (e.glb || "").replace(/^\.?\//, "");
    if (MISSING_HERO_GLBS.has(g)) { e._loading = true; n++; }
  }
  return n;
}
