// Build addons/src/outfits/index.ts from the numbered outfit files.
// A new variant is a new file. This index is generated so outfit PRs do not
// edit a shared list.
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = join(dirname(fileURLToPath(import.meta.url)), "../src/outfits");
const files = readdirSync(dir)
  .filter((name) => /^\d+-.+\.ts$/.test(name))
  .sort((a, b) => {
    const na = parseInt(a, 10);
    const nb = parseInt(b, 10);
    if (na !== nb) return na - nb;
    return a < b ? -1 : a > b ? 1 : 0;
  });
if (!files.length) {
  console.error("no outfit files");
  process.exit(1);
}
const lines = [
  "// Generated by addons/scripts/gen-outfits.mjs. Do not edit.",
  'import type { BeachOutfit } from "../npcBake";',
  ...files.map(
    (name, index) =>
      `import { outfit as outfit${index} } from "./${name.replace(/\.ts$/, "")}";`,
  ),
  "",
  "export const BEACH_OUTFITS: readonly BeachOutfit[] = [",
  ...files.map((_, index) => `  outfit${index},`),
  "];",
  "",
];
writeFileSync(join(dir, "index.ts"), lines.join("\n"));
console.log(`outfits ${files.length}`);
